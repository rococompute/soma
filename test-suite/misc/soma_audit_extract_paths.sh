#!/usr/bin/env bash

# F8: the generated Soma source that extraction runs writes its destination
# with Soma (Rocq) string quoting, where a double quote is doubled and a
# backslash is itself. OCaml's %S quoting instead writes \" and \\, so a
# destination with a quote did not parse, and one with a backslash named a
# doubled-backslash directory while the rest of the project went to the
# requested one. The MirageOS extraction staging path uses the same source.

set -euo pipefail

export PATH="$BIN:$PATH"
export SOMA_OCAML_BUILD=0
export SOMA_MIRAGE_BUILD=0
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
export SOMA_CACHE="$TMP/soma-cache"
export XDG_CACHE_HOME="$TMP/xdg"
mkdir -p "$XDG_CACHE_HOME"
cd "$TMP"

cat > main.soma <<'SOMA'
main : nat := 1.
SOMA

export SOMA_TEST_FIXTURE="$TMP"
python3 - <<'PY'
import os
import pathlib
import subprocess
import sys

root = pathlib.Path(os.environ['SOMA_TEST_FIXTURE'])

def run(args, **kwargs):
    result = subprocess.run(args, text=True, capture_output=True, **kwargs)
    if result.returncode:
        sys.stderr.write(' '.join(map(str, args)) + '\n' + result.stdout + result.stderr)
    return result

def extract(dest, cwd=root, source='main.soma'):
    return run(['soma', 'extract', source, '-o', str(dest)], cwd=cwd)

# Every representable path character, including the ones %S escapes
# differently from Rocq (quote, backslash, newline, tab). Spaces, quotes
# of the other kind, and punctuation are checked too.
names = [
    'plain',
    'with space',
    'with"quote',
    'two""quotes',
    'trailing"',
    '"leading',
    'with\\backslash',
    'trailing\\',
    "with'single",
    'with[brackets]',
    'with%percent',
    'with$dollar',
    'with=equals',
    'with#hash',
    'with;semicolon',
    'with(newline)\nsecond',
    'with\ttab',
    'with\x01control',
    'with\x7fdelete',
    'with\u00e9utf8',
    'all "quote" \\ slash\nnewline\tand space',
]

parent = root / 'native'
parent.mkdir()
for name in names:
    dest = parent / name
    before = set(os.listdir(parent))
    result = extract(dest)
    assert result.returncode == 0, (name, result.returncode)
    # Extraction itself must have written prog.ml into the requested
    # directory, not a sibling whose name %S made with an extra backslash.
    for made in ('prog.ml', 'prog.mli', 'soma_main.ml', 'dune-project'):
        assert (dest / made).is_file(), (name, made, sorted(os.listdir(parent)))
    assert 'soma_main' in (dest / 'prog.ml').read_text(), name
    after = set(os.listdir(parent))
    assert after == before | {name}, (name, sorted(after - before - {name}))

# Without -o, the project goes next to the source, in a directory whose
# name is made from a source directory that also needs quoting.
source_dir = root / 'source "q"\\ dir'
source_dir.mkdir()
(source_dir / 'main.soma').write_text('main : nat := 1.\n')
result = run(['soma', 'extract', 'main.soma'], cwd=source_dir)
assert result.returncode == 0, result.returncode
assert (source_dir / 'main-ocaml' / 'prog.ml').is_file()

# Inspect the generated source itself, for an ordinary path and for one
# that needs quoting. Extraction fails after writing extract.soma when
# prog.ml is already a directory, which leaves the generated file for us to
# read. The destination line must be exactly Rocq's quoting: quotes
# doubled, the backslash unchanged.
for rep_name in ('representation-plain', 'representation "q"\\dir'):
    representation = root / rep_name
    representation.mkdir()
    (representation / 'prog.ml').mkdir()
    (representation / 'dune-project').write_text(
        '(lang dune 3.0)\n'
        '; Generated by Soma (toplevel/somaOcaml.ml): soma extract main.soma\n')
    result = subprocess.run(['soma', 'extract', 'main.soma', '-o', str(representation)],
                            text=True, capture_output=True)
    assert result.returncode != 0, (rep_name, 'extraction into a prog.ml directory should fail')
    cmds = (representation / 'extract.soma').read_text()
    line = next(l for l in cmds.splitlines()
                if l.startswith('Set Extraction Output Directory '))
    expected = ('Set Extraction Output Directory "'
                + str(representation).replace('"', '""') + '".')
    assert line == expected, (rep_name, line, expected)

# The MirageOS extraction writes the same generated source, into a staging
# directory under SOMA_MIRAGE_DIR. A quote or backslash there must not stop
# the staging extraction; --no-image stops before the Solo5 toolchain.
mirage_root = root / 'mirage "q"\\ dir'
env = os.environ.copy()
env.pop('SOMA_MIRAGE_BUILD', None)
env.pop('SOMA_MIRAGE_SWITCH', None)
env['SOMA_MIRAGE_DIR'] = str(mirage_root)
env['SOMA_MIRAGE_NO_IMAGE'] = '1'
program = root / 'sandbox'
program.mkdir()
(program / 'main.soma').write_text(
    'Require Import Sandbox.\n'
    'main := print "hi".\n')
result = run(['soma', 'build', '--no-image', 'main.soma'], cwd=program, env=env)
assert result.returncode == 0, result.returncode
assert (mirage_root / 'plain' / 'prog.ml').is_file(), sorted(os.listdir(mirage_root))
assert 'soma_main' in (mirage_root / 'plain' / 'prog.ml').read_text()
assert (mirage_root / 'extract' / 'prog.ml').is_file()
# The Mirage extraction leaves its generated source in the staging
# directory; it must use the same Rocq quoting as the host extraction.
mirage_cmds = (mirage_root / 'extract' / 'extract.soma').read_text()
mirage_line = next(l for l in mirage_cmds.splitlines()
                   if l.startswith('Set Extraction Output Directory '))
mirage_expected = ('Set Extraction Output Directory "'
                   + str(mirage_root / 'extract').replace('"', '""') + '".')
assert mirage_line == mirage_expected, (mirage_line, mirage_expected)
# no directory made by OCaml-style doubled backslashes
assert not any('\\\\' in p.name for p in mirage_root.iterdir()), \
    [p.name for p in mirage_root.iterdir()]

print('soma audit extraction path quoting: passed')
PY
