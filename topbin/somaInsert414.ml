(* OCaml source insertion. Parsing and type inference use compiler-libs;
   accepted declarations become ordinary, kernel-checked Soma source.
   No source evaluation, PPX, extraction escape, axioms or gradual holes. *)
open Asttypes
open Typedtree

exception Unsupported of Location.t * string * string
let unsupported loc code message = raise (Unsupported (loc, code, message))
let fail loc message = unsupported loc "unsupported" message
let encode s =
  let b = Buffer.create (String.length s) in
  String.iter (fun c -> match c with
    | 'a'..'z' | 'A'..'Z' | '0'..'9' -> Buffer.add_char b c
    | _ -> Buffer.add_string b (Printf.sprintf "_%02x" (Char.code c))) s;
  Buffer.contents b
let value id = "oc_" ^ encode (Ident.name id)
let type_name id = "oct_" ^ encode (Ident.name id)
let app f args = if args = [] then f else "(" ^ f ^ " " ^ String.concat " " args ^ ")"
let location_key loc = loc.Location.loc_start.Lexing.pos_cnum
let path_name = Path.name
let rec stdlib_path = function
  | Path.Pident id -> Ident.persistent id &&
      (let name=Ident.name id in name="Stdlib" ||
       (String.length name>8 && String.sub name 0 8="Stdlib__"))
  | Path.Pdot (p,_) -> stdlib_path p
  | Path.Papply _ -> false
let type_key p =
  match List.find_opt (fun (path,_) -> Path.same p path)
      [Predef.path_int,"int"; Predef.path_char,"char"; Predef.path_string,"string";
       Predef.path_bool,"bool"; Predef.path_unit,"unit"; Predef.path_list,"list";
       Predef.path_option,"option"] with
  | Some (_,name) -> name
  | None when stdlib_path p && Path.name p="Stdlib.result" -> "result"
  | None -> "ocaml:" ^ Path.name p
let base_type ty = match Types.get_desc ty with
  | Types.Tconstr (p, _, _) -> type_key p | _ -> ""
let builtin name ty = base_type ty = name
let int_literal n =
  Printf.sprintf "%Ld%%uint63" (Int64.logand (Int64.of_int n) Int64.max_int)
let char_term c =
  let bits = List.init 8 (fun i -> if Char.code c land (1 lsl i) <> 0 then "true" else "false") in
  app "Ascii.Ascii" bits
let string_term s =
  if String.for_all (fun c -> c >= ' ' && c <= '~' && c <> '\\') s then
    "\"" ^ String.concat "" (List.map (function '"' -> "\"\"" | c -> String.make 1 c)
      (List.init (String.length s) (String.get s))) ^ "\""
  else begin
  let result = ref "String.EmptyString" in
  for i = String.length s - 1 downto 0 do
    result := app "String.String" [char_term s.[i]; !result]
  done;
  !result
  end

let header = {|(* Generated by soma insert. Ordinary Soma; OCaml int uses 63-bit words.
   Accepted declarations have been checked by soma check. See insert-report.json
   for omissions. No unsupported source was replaced with an implementation. *)
From Corelib Require Import PrimInt63 Sint63Axioms.
From Stdlib Require Import List Strings.String Strings.Ascii Numbers.DecimalString.
Import ListNotations.
Set Implicit Arguments.

Fixpoint insert_int_of_nat (n : nat) : PrimInt63.int :=
  match n with
  | O => 0%uint63
  | S k => PrimInt63.add 1%uint63 (insert_int_of_nat k)
  end.

Fixpoint insert_split (sep : ascii) (s : string) : list string :=
  match s with
  | EmptyString => [EmptyString]
  | String c rest =>
    let tail := insert_split sep rest in
    if Ascii.eqb c sep then EmptyString :: tail
    else match tail with
         | [] => [String c EmptyString]
         | h :: t => String c h :: t
         end
  end.

Definition insert_concat (sep : string) (xs : list string) : string :=
  match xs with
  | [] => EmptyString
  | h :: rest => List.fold_left (fun acc s => String.append acc (String.append sep s)) rest h
  end.

Definition insert_string_of_int (n : PrimInt63.int) : string :=
  DecimalString.NilZero.string_of_int (BinIntDef.Z.to_int (Sint63Axioms.to_Z n)).

Fixpoint insert_filter_map {A B : Type} (f : A -> option B) (xs : list A) : list B :=
  match xs with
  | [] => []
  | x :: rest => match f x with None => insert_filter_map f rest | Some y => y :: insert_filter_map f rest end
  end.

|}

type context = {
  mutable values : (Ident.t * string) list;
  mutable types : (string * string) list;
  mutable variables : (int * string) list;
  mutable next_variable : int;
}
let context () = { values=[]; types=[]; variables=[]; next_variable=0 }
let rec lookup_value id = function
  | [] -> None
  | (id', name) :: rest -> if Ident.same id id' then Some name else lookup_value id rest
let type_variable c ty =
    match List.assoc_opt (Types.get_id ty) c.variables with
  | Some n -> n
  | None ->
    let n = "a" ^ string_of_int c.next_variable in
    c.next_variable <- c.next_variable + 1;
    c.variables <- c.variables @ [(Types.get_id ty), n]; n
let rec typ c loc ty =
    match Types.get_desc ty with
  | Types.Tvar _ | Types.Tunivar _ -> type_variable c ty
  | Types.Tarrow (label, a, b, _) ->
    (match label with Optional _ -> fail loc "optional arguments need an explicit calling convention" | _ -> ());
    "(" ^ typ c loc a ^ " -> " ^ typ c loc b ^ ")"
  | Types.Ttuple ts -> "(" ^ String.concat " * " (List.map (typ c loc) ts) ^ ")%type"
  | Types.Tconstr (p, args, _) ->
    let name = type_key p in
    let target = match name with
      | "int" -> "PrimInt63.int" | "bool" -> "bool" | "unit" -> "unit"
      | "string" -> "string" | "char" -> "ascii" | "list" -> "list"
      | "option" -> "option" | "result" | "Stdlib.result" -> "sum"
      | _ -> (match List.assoc_opt name c.types with
          | Some n -> n
          | None -> unsupported loc "type" ("type needs a translation: " ^ name)) in
    app target (List.map (typ c loc) args)
  | _ -> unsupported loc "type" "object, polymorphic variant, package or higher-rank type needs a translation"
let parameters c = String.concat " " (List.map (fun (_, n) -> "{" ^ n ^ " : Type}") c.variables)
let constructor c loc desc =
  match base_type desc.Types.cstr_res, desc.Types.cstr_name with
  | "bool", "true" -> "true" | "bool", "false" -> "false"
  | "unit", "()" -> "tt"
  | "list", "[]" -> "nil" | "list", "::" -> "cons"
  | "option", "None" -> "None" | "option", "Some" -> "Some"
  | ("result" | "Stdlib.result"), "Ok" -> "inl"
  | ("result" | "Stdlib.result"), "Error" -> "inr"
  | owner, name ->
    let owner = match List.assoc_opt owner c.types with
      | Some n -> n | None -> unsupported loc "dependency" ("constructor belongs to an untranslated type: " ^ owner) in
    "occ_" ^ owner ^ "_" ^ encode name
let field c loc desc =
  if desc.Types.lbl_mut = Mutable then unsupported loc "mutation" "mutable record fields require an identity-preserving state translation";
  let owner = base_type desc.Types.lbl_res in
  match List.assoc_opt owner c.types with
  | Some n -> "ocf_" ^ n ^ "_" ^ encode desc.Types.lbl_name
  | None -> unsupported loc "dependency" ("field belongs to an untranslated type: " ^ owner)
let rec equal loc ty a b =
  match base_type ty with
  | "int" -> app "PrimInt63.eqb" [a;b]
  | "bool" -> app "Bool.eqb" [a;b]
  | "string" -> app "String.eqb" [a;b]
  | "char" -> app "Ascii.eqb" [a;b]
  | "unit" -> "true"
  | _ -> unsupported loc "equality" "structural equality for this type needs a translation"
let constant loc = function
  | Const_int n -> int_literal n
  | Const_char c -> char_term c
  | Const_string (s, _, _) -> string_term s
  | _ -> unsupported loc "number" "floats, int32, int64 and nativeint need separate numeric translations"

let rec pattern : type k. context -> k general_pattern -> string * (Ident.t * string) list = fun c p ->
  match p.pat_desc with
  | Tpat_any -> "_", []
  | Tpat_var (id, _) -> value id, [id, value id]
  | Tpat_alias (p, id, _) -> let s, ids = pattern c p in "(" ^ s ^ " as " ^ value id ^ ")", (id,value id)::ids
  | Tpat_value p -> pattern c (p :> pattern)
  | Tpat_constant (Const_int _) -> unsupported p.pat_loc "integer-pattern" "integer patterns are translated only at the top level of a match"
  | Tpat_constant k -> constant p.pat_loc k, []
  | Tpat_tuple ps ->
    let ss, ids = List.split (List.map (pattern c) ps) in
    "(" ^ String.concat ", " ss ^ ")", List.concat ids
  | Tpat_construct (_, desc, ps, _) ->
    let ss, ids = List.split (List.map (pattern c) ps) in
    app (constructor c p.pat_loc desc) ss, List.concat ids
  | Tpat_record (fs, _) ->
    let ss, ids = List.split (List.map (fun (_, desc, p) ->
      let s, ids = pattern c p in field c p.pat_loc desc ^ " := " ^ s, ids) fs) in
    "{| " ^ String.concat "; " ss ^ " |}", List.concat ids
  | _ -> unsupported p.pat_loc "pattern" "or-patterns, exception patterns and polymorphic variants need a translation"

let stdlib_name p =
  let name = path_name p in
  if String.length name > 7 && String.sub name 0 7 = "Stdlib." then
    String.sub name 7 (String.length name - 7) else name
let rec integer_pattern : type k. k general_pattern -> bool = fun p ->
  match p.pat_desc with
  | Tpat_constant (Const_int _) -> true
  | Tpat_value p -> integer_pattern (p :> pattern)
  | _ -> false
let rec expr c scope e =
  let go = expr c scope in
  match e.exp_desc with
  | Texp_ident (Path.Pident id, _, _) when lookup_value id (scope @ c.values) <> None ->
    Option.get (lookup_value id (scope @ c.values))
  | Texp_ident (p, _, _) -> standard c scope e p []
  | Texp_constant k -> constant e.exp_loc k
  | Texp_tuple es -> "(" ^ String.concat ", " (List.map go es) ^ ")"
  | Texp_construct (_, desc, es) -> app (constructor c e.exp_loc desc) (List.map go es)
  | Texp_ifthenelse (a,b,Some d) -> "(if " ^ go a ^ " then " ^ go b ^ " else " ^ go d ^ ")"
  | Texp_function {arg_label=Optional _;_} -> fail e.exp_loc "optional arguments need an explicit calling convention"
  | Texp_function {cases=[{c_lhs={pat_desc=Tpat_var (id,_);_};c_guard=None;c_rhs}];_} ->
    let input=match Types.get_desc e.exp_type with Types.Tarrow (_,a,_,_) -> a | _ -> assert false in
    "(fun (" ^ value id ^ " : " ^ typ c e.exp_loc input ^ ") -> " ^ expr c ((id,value id)::scope) c_rhs ^ ")"
  | Texp_function {param=_;cases;partial;_} ->
    let input = match Types.get_desc e.exp_type with
      | Types.Tarrow (_, a, _, _) -> a | _ -> assert false in
    let arg = "insert_arg_" ^ string_of_int (location_key e.exp_loc) in
    "(fun (" ^ arg ^ " : " ^ typ c e.exp_loc input ^ ") -> " ^
    cases_expr c scope e.exp_loc partial arg cases ^ ")"
  | Texp_match (arg, cases, partial) -> cases_expr c scope e.exp_loc partial (go arg) cases
  | Texp_apply (f, args) ->
    let args = List.map (function
      | Optional _, _ -> fail e.exp_loc "optional application needs a calling-convention translation"
      | _, Some x -> x
      | _, None -> fail e.exp_loc "partially supplied labeled arguments need a translation") args in
    (match f.exp_desc with
     | Texp_ident (Path.Pident id,_,_) when lookup_value id (scope @ c.values) <> None -> app (go f) (List.map go args)
     | Texp_ident (p,_,_) -> standard c scope e p args
     | _ -> app (go f) (List.map go args))
  | Texp_let (Nonrecursive, bindings, body) ->
    (* ML parallel lets now preserve the OCaml RHS scope directly. Keep
       temporaries only when parallel destructuring needs a second stage. *)
    let simple=List.for_all (fun vb -> match vb.vb_pat.pat_desc with Tpat_var _ -> true | _ -> false) bindings in
    let bindings=List.mapi (fun i vb ->
      let p,ids=pattern c vb.vb_pat in
      let temp="insert_let_" ^ string_of_int (location_key e.exp_loc) ^ "_" ^ string_of_int i in
      temp,go vb.vb_expr,p,ids) bindings in
    let ids=List.concat_map (fun (_,_,_,ids)->ids) bindings in
    let body=expr c (ids @ scope) body in
    let named bindings body = "(let " ^ String.concat " and " bindings ^ " in " ^ body ^ ")" in
    if simple then named (List.map (fun (_,rhs,p,_)->p ^ " = " ^ rhs) bindings) body
    else
      let body=List.fold_right (fun (temp,_,p,_) body -> "(let (" ^ p ^ ") = " ^ temp ^ " in " ^ body ^ ")") bindings body in
      named (List.map (fun (temp,rhs,_,_)->temp ^ " = " ^ rhs) bindings) body
  | Texp_let (Recursive, _, _) -> unsupported e.exp_loc "recursion" "local recursive functions need lifting and structural-recursion analysis"
  | Texp_record {fields; extended_expression;_} ->
    (* Rebuilding immutable records preserves their value semantics. *)
    let fields = Array.to_list fields |> List.map (fun (d, def) ->
      let label = field c e.exp_loc d in
      let rhs = match def, extended_expression with
        | Overridden (_, e), _ -> go e
        | Kept _, Some base -> app label [go base]
        | _ -> assert false in
      (* Record delimiters embed ordinary Soma fields, so explicitly re-enter
         ML syntax for a field's potentially compound expression. *)
      label ^ " := ml { " ^ rhs ^ " }") in
    "{| " ^ String.concat "; " fields ^ " |}"
  | Texp_field (obj,_,desc) -> app (field c e.exp_loc desc) [go obj]
  | Texp_open (_,body) -> go body
  | Texp_setfield _ -> unsupported e.exp_loc "mutation" "field assignment requires effect and alias analysis"
  | Texp_try _ -> unsupported e.exp_loc "exception" "exception handling requires an explicit error/effect translation"
  | Texp_for _ | Texp_while _ -> unsupported e.exp_loc "loop" "imperative loops require an effectful loop translation"
  | Texp_sequence _ -> unsupported e.exp_loc "effect" "sequencing requires an effect translation"
  | _ -> fail e.exp_loc "this expression is outside the initial pure subset"
and cases_expr : type k. context -> (Ident.t * string) list -> Location.t -> partial -> string -> k case list -> string =
  fun c scope loc partial arg cases ->
  if partial = Partial then unsupported loc "partial-match" "non-exhaustive matches require an explicit failure translation";
  if List.exists (fun case -> case.c_guard <> None) cases then fail loc "guarded patterns need decision-tree translation";
  let has_int = List.exists (fun case -> integer_pattern case.c_lhs) cases in
  if has_int then
    let rec branch arg = function
      | [] -> unsupported loc "integer-pattern" "integer cases must end with a wildcard or variable"
      | case :: rest ->
        let rec inspect : type k. k general_pattern -> string = fun p -> match p.pat_desc with
          | Tpat_value p -> inspect (p :> pattern)
          | Tpat_constant (Const_int n) ->
            "(if " ^ app "PrimInt63.eqb" [arg;int_literal n] ^ " then " ^
            expr c scope case.c_rhs ^ " else " ^ branch arg rest ^ ")"
          | Tpat_any when rest=[] -> expr c scope case.c_rhs
          | Tpat_var (id,_) when rest=[] ->
            "(let " ^ value id ^ " = " ^ arg ^ " in " ^ expr c ((id,value id)::scope) case.c_rhs ^ ")"
          | _ -> fail p.pat_loc "mixed integer and non-integer patterns need decision-tree translation" in
        inspect case.c_lhs in
    (* Evaluate the scrutinee once; it may itself be a sizeable pure term. *)
    let name = "insert_match_" ^ string_of_int (location_key loc) in
    "(let " ^ name ^ " = " ^ arg ^ " in " ^ branch name cases ^ ")"
  else
    "(match " ^ arg ^ " with " ^ String.concat " " (List.map (fun case ->
      let p, ids = pattern c case.c_lhs in
      "| " ^ p ^ " -> " ^ expr c (ids @ scope) case.c_rhs) cases) ^ ")"
and standard c scope e path args =
  if not (stdlib_path path) then
    unsupported e.exp_loc "dependency" ("value is not a translated declaration or OCaml Stdlib binding: " ^ Path.name path);
  let name = stdlib_name path in
  let go = expr c scope in
  let direct f = app f (List.map go args) in
  let unary f = match args with [a] -> app f [go a] | _ -> fail e.exp_loc ("fully apply " ^ name) in
  let binary f = match args with [a;b] -> app f [go a;go b] | _ -> fail e.exp_loc ("fully apply " ^ name) in
  let comparison eq negate = match args with
    | [a;b] ->
      let is_nil e = match e.exp_desc with Texp_construct (_,d,[]) -> base_type d.Types.cstr_res="list" && d.Types.cstr_name="[]" | _ -> false in
      let result = if builtin "list" a.exp_type && (is_nil a || is_nil b) then
          "(match " ^ go (if is_nil a then b else a) ^ " with nil -> true | _ -> false)"
        else eq a.exp_type (go a) (go b) in
      if negate then app "negb" [result] else result
    | [a] ->
      let result=eq a.exp_type (go a) "insert_equal_arg" in
      "(fun (insert_equal_arg : " ^ typ c e.exp_loc a.exp_type ^ ") -> " ^
        (if negate then app "negb" [result] else result) ^ ")"
    | _ -> fail e.exp_loc ("fully apply " ^ name) in
  match name with
  | "+" | "-" | "*" | "land" | "lor" | "lxor" ->
    binary ("PrimInt63." ^ List.assoc name ["+","add";"-","sub";"*","mul";"land","land";"lor","lor";"lxor","lxor"])
  | "~-" -> (match args with [a] -> app "PrimInt63.sub" ["0%uint63";go a] | _ -> fail e.exp_loc "fully apply negation")
  | "lnot" -> (match args with [a] -> app "PrimInt63.lxor" ["9223372036854775807%uint63";go a] | _ -> fail e.exp_loc "fully apply lnot")
  | "lsl" | "lsr" | "asr" ->
    (match args with
    | [a; ({exp_desc=Texp_constant (Const_int n);_} as b)] when n >= 0 && n < 63 ->
      app ("PrimInt63." ^ name) [go a;go b]
    | _ -> unsupported e.exp_loc "shift" "shift counts must be literal integers in 0..62")
  | "/" | "mod" -> unsupported e.exp_loc "exception" "division needs a zero-divisor failure translation"
  | "=" -> comparison (equal e.exp_loc) false
  | "<>" -> comparison (equal e.exp_loc) true
  | "<" | "<=" | ">" | ">=" ->
    (match args with
    | [a;b] when builtin "int" a.exp_type ->
      let f = if name="<" || name=">" then "PrimInt63.ltsb" else "PrimInt63.lesb" in
      if name=">" || name=">=" then app f [go b;go a] else app f [go a;go b]
    | _ -> fail e.exp_loc "ordered comparison initially supports signed OCaml int")
  | "&&" -> (match args with [a;b] -> "(if " ^ go a ^ " then " ^ go b ^ " else false)" | _ -> fail e.exp_loc "fully apply &&")
  | "||" -> (match args with [a;b] -> "(if " ^ go a ^ " then true else " ^ go b ^ ")" | _ -> fail e.exp_loc "fully apply ||")
  | "not" -> unary "negb"
  | "min" | "max" -> (match args with
    | [a;b] when builtin "int" a.exp_type ->
      "(if " ^ app "PrimInt63.lesb" [go a;go b] ^ " then " ^ go (if name="min" then a else b) ^ " else " ^ go (if name="min" then b else a) ^ ")"
    | _ -> fail e.exp_loc "min/max initially support fully applied signed integers")
  | "^" | "String.cat" -> binary "String.append"
  | "String.equal" -> binary "String.eqb"
  | "Char.equal" -> binary "Ascii.eqb"
  | "String.length" -> (match args with [a] -> app "insert_int_of_nat" [app "String.length" [go a]] | _ -> fail e.exp_loc "fully apply String.length")
  | "String.split_on_char" -> binary "insert_split"
  | "String.concat" -> binary "insert_concat"
  | "string_of_int" -> unary "insert_string_of_int"
  | "String.make" -> (match args with
    | [{exp_desc=Texp_constant (Const_int n);_};ch] when n>=0 && n<=1024 ->
      let rec make n = if n=0 then "String.EmptyString" else app "String.String" [go ch;make (n-1)] in make n
    | _ -> fail e.exp_loc "String.make initially requires a literal length in 0..1024")
  | "List.length" -> (match args with [a] -> app "insert_int_of_nat" [app "List.length" [go a]] | _ -> fail e.exp_loc "fully apply List.length")
  | "List.map" -> direct "List.map"
  | "List.rev" -> direct "List.rev"
  | "List.filter" -> direct "List.filter"
  | "List.exists" -> direct "List.existsb"
  | "List.for_all" -> direct "List.forallb"
  | "List.filter_map" -> direct "insert_filter_map"
  | "List.append" | "@" -> direct "List.app"
  | "List.fold_right" -> direct "List.fold_right"
  | "List.fold_left" -> (match args with [f;init;xs] -> app "List.fold_left" [go f;go xs;go init] | _ -> fail e.exp_loc "fully apply List.fold_left")
  | "fst" -> direct "fst" | "snd" -> direct "snd"
  | "min_int" -> "4611686018427387904%uint63"
  | "max_int" -> "4611686018427387903%uint63"
  | "ref" | "!" | ":=" | "incr" | "decr" -> unsupported e.exp_loc "mutation" (name ^ " requires identity-preserving cells and effect propagation")
  | _ -> unsupported e.exp_loc "dependency" ("value needs a translation or binding: " ^ Path.name path)

let rec collect_variables c ty =
  let seen = Hashtbl.create 16 in
  let rec visit ty =
        if not (Hashtbl.mem seen (Types.get_id ty)) then begin
      Hashtbl.add seen (Types.get_id ty) ();
      match Types.get_desc ty with
      | Types.Tvar _ | Types.Tunivar _ -> ignore (type_variable c ty)
      | _ -> Btype.iter_type_expr visit ty
    end in
  visit ty
let reset_variables c = c.variables <- []; c.next_variable <- 0
let snapshot c = c.values, c.types, c.variables, c.next_variable
let restore c (vs,ts,vars,next) = c.values <- vs; c.types <- ts; c.variables <- vars; c.next_variable <- next
let top_binding c recursive vb =
  let id = match vb.vb_pat.pat_desc with Tpat_var (id,_) -> id
    | _ -> fail vb.vb_loc "top-level bindings must name a value; initializers and destructuring need a translation" in
  reset_variables c;
  collect_variables c vb.vb_expr.exp_type;
  let name = value id in
  let scope = if recursive then [id,name] else [] in
  let signature = typ c vb.vb_loc vb.vb_expr.exp_type in
  let signature_variables = c.next_variable in
  let body = if not recursive then expr c [] vb.vb_expr else
    let rec arguments acc e = match e.exp_desc with
      | Texp_function {arg_label=Optional _;_} -> fail e.exp_loc "optional recursive arguments need a translation"
      | Texp_function {cases=[{c_lhs={pat_desc=Tpat_var (id,_);_};c_guard=None;c_rhs}];_} ->
        let input = match Types.get_desc e.exp_type with Types.Tarrow (_,a,_,_) -> a | _ -> assert false in
        arguments (acc @ [id,input]) c_rhs
      | _ -> acc,e in
    let args, body = arguments [] vb.vb_expr in
    if args=[] then unsupported vb.vb_loc "recursion" "recursive function arguments must be named";
    let structural = List.find_opt (fun (_,ty) -> builtin "list" ty || List.mem_assoc (base_type ty) c.types) args in
    let id = match structural with Some (id,_) -> id
      | None -> unsupported vb.vb_loc "recursion" "recursion on machine integers requires a separate termination/effect translation" in
    let scope = List.map (fun (id,_) -> id,value id) args @ scope in
    let binders = List.map (fun (id,ty) -> "(" ^ value id ^ " : " ^ typ c vb.vb_loc ty ^ ")") args in
    let result = List.fold_left (fun ty _ -> match Types.get_desc ty with Types.Tarrow (_,_,b,_) -> b | _ -> assert false) vb.vb_expr.exp_type args in
    "@@FIX@@" ^ String.concat " " binders ^ " {struct " ^ value id ^ "} : " ^ typ c vb.vb_loc result ^ " := ml { " ^ expr c scope body ^ " }" in
  (* New existential variables in local expressions cannot be implicitly made
     into global parameters; that would misrepresent OCaml let polymorphism. *)
  if c.next_variable <> signature_variables then
    unsupported vb.vb_loc "let-polymorphism" "local type variables need explicit polymorphic-let translation";
  let vars = parameters c in
  let text = if recursive then
      "Fixpoint " ^ name ^ " " ^ vars ^ " " ^ String.sub body 7 (String.length body-7) ^ ".\n"
    else "Definition " ^ name ^ " " ^ vars ^ " : " ^ signature ^ " := ml { " ^ body ^ " }.\n" in
  c.values <- (id,name)::c.values;
  text

let type_declaration c decl =
  reset_variables c;
  let t = decl.typ_type in
  if t.Types.type_private=Private then fail decl.typ_loc "private types need an abstraction-preserving translation";
  List.iter (collect_variables c) t.Types.type_params;
  let name = type_name decl.typ_id in
  let params = List.map (typ c decl.typ_loc) t.Types.type_params in
  let binders = String.concat " " (List.map (fun p -> "(" ^ p ^ " : Type)") params) in
  let self = app name params in
  match t.Types.type_kind, t.Types.type_manifest with
  | Types.Type_abstract, Some ty ->
    "Definition " ^ name ^ " " ^ binders ^ " : Type := " ^ typ c decl.typ_loc ty ^ ".\n"
  | Types.Type_record (fields,_), _ ->
    let fs = List.map (fun f ->
      if f.Types.ld_mutable=Mutable then unsupported f.Types.ld_loc "mutation" "mutable record types require an identity-preserving state representation";
      "ocf_" ^ name ^ "_" ^ encode (Ident.name f.Types.ld_id) ^ " : " ^ typ c f.Types.ld_loc f.Types.ld_type) fields in
    "Record " ^ name ^ " " ^ binders ^ " : Type := ocmk_" ^ name ^ " { " ^ String.concat "; " fs ^ " }.\n"
  | Types.Type_variant (ctors,_), _ ->
    let ctors = List.map (fun d ->
      if d.Types.cd_res <> None then fail d.Types.cd_loc "GADT constructors need dependent result translation";
      let args = match d.Types.cd_args with Types.Cstr_tuple args -> args | _ -> fail d.Types.cd_loc "inline record constructors need lifting" in
      "| occ_" ^ name ^ "_" ^ encode (Ident.name d.Types.cd_id) ^ " : " ^
      String.concat " -> " (List.map (typ c d.Types.cd_loc) args @ [self])) ctors in
    "Inductive " ^ name ^ " " ^ binders ^ " : Type :=\n" ^ String.concat "\n" ctors ^ ".\n"
  | _ -> unsupported decl.typ_loc "type" "abstract or extensible types need an explicit representation"
let item c item = match item.str_desc with
  | Tstr_value (recflag,[vb]) -> top_binding c (recflag=Recursive) vb
  | Tstr_value (Nonrecursive, bindings) -> String.concat "\n" (List.map (top_binding c false) bindings)
  | Tstr_value _ -> fail item.str_loc "mutually recursive top-level bindings need lifting"
  | Tstr_type (_, [decl]) ->
    c.types <- (type_key (Path.Pident decl.typ_id),type_name decl.typ_id)::c.types;
    type_declaration c decl
  | Tstr_type _ -> fail item.str_loc "mutually recursive types need a translation"
  | Tstr_open _ -> ""
  | Tstr_attribute _ -> fail item.str_loc "source attributes are not executed or propagated"
  | Tstr_primitive _ -> unsupported item.str_loc "native-binding" "external primitives need Soma .definition/C bindings"
  | Tstr_exception _ -> unsupported item.str_loc "exception" "exceptions need an explicit error representation"
  | _ -> fail item.str_loc "modules, classes, includes and initialization expressions need a translation"

let json_string s =
  let b = Buffer.create (String.length s+2) in
  Buffer.add_char b '"';
  String.iter (function
    | '"' -> Buffer.add_string b "\\\"" | '\\' -> Buffer.add_string b "\\\\"
    | '\n' -> Buffer.add_string b "\\n" | '\r' -> Buffer.add_string b "\\r" | '\t' -> Buffer.add_string b "\\t"
    | c when Char.code c < 32 -> Buffer.add_string b (Printf.sprintf "\\u%04x" (Char.code c))
    | c -> Buffer.add_char b c) s;
  Buffer.add_char b '"'; Buffer.contents b
let read_file p = let ic=open_in_bin p in Fun.protect ~finally:(fun () -> close_in ic) (fun () -> really_input_string ic (in_channel_length ic))
let write_new p text =
  let fd = Unix.openfile p [Unix.O_WRONLY;Unix.O_CREAT;Unix.O_EXCL] 0o600 in
  let oc=Unix.out_channel_of_descr fd in Fun.protect ~finally:(fun () -> close_out oc) (fun () -> output_string oc text)
let checking = ref None
let rec wait pid =
  try snd (Unix.waitpid [] pid) with Unix.Unix_error (Unix.EINTR,_,_) -> wait pid
let pass_signals () =
  List.iter (fun signal -> Sys.set_signal signal (Sys.Signal_handle (fun signal ->
    Option.iter (fun pid ->
      (try Unix.kill pid signal with Unix.Unix_error _ -> ());
      (try ignore (wait pid) with Unix.Unix_error _ -> ())) !checking;
    exit (if signal=Sys.sigint then 130 else 143)))) [Sys.sigint;Sys.sigterm;Sys.sighup]
let rec mkdir p = if not (Sys.file_exists p) then begin mkdir (Filename.dirname p); Unix.mkdir p 0o755 end
let rec remove_tree p =
  if (Unix.lstat p).Unix.st_kind=Unix.S_DIR then begin Array.iter (fun n -> remove_tree (Filename.concat p n)) (Sys.readdir p); Unix.rmdir p end else Sys.remove p
let with_temp f =
  let p=Filename.temp_file "soma-insert-" "" in Sys.remove p; Unix.mkdir p 0o700;
  Fun.protect ~finally:(fun () -> remove_tree p) (fun () -> f p)
let check checker work text =
  let source=Filename.concat work "inserted.soma" and log=Filename.concat work "check.log" in
  let oc=open_out_bin source in output_string oc text; close_out oc;
  let fd=Unix.openfile log [Unix.O_WRONLY;Unix.O_CREAT;Unix.O_TRUNC] 0o600 in
  let status=Fun.protect ~finally:(fun () -> Unix.close fd) (fun () ->
    let pid=Unix.create_process checker [|checker;"check";source|] Unix.stdin fd fd in
    checking:=Some pid;
    Fun.protect ~finally:(fun () -> checking:=None) (fun () -> wait pid)) in
  match status with Unix.WEXITED 0 -> None | _ -> Some (read_file log)

type diagnostic = {loc:Location.t;code:string;message:string}
type segment = {text:string;loc:Location.t}
type result = {source:string;relative:string;items:int;mutable segments:segment list;mutable diagnostics:diagnostic list}
let diagnostic_json (d : diagnostic) =
  let p=d.loc.Location.loc_start in
  Printf.sprintf "{\"line\":%d,\"column\":%d,\"code\":%s,\"message\":%s}" p.Lexing.pos_lnum (p.pos_cnum-p.pos_bol+1) (json_string d.code) (json_string d.message)
let result_json r = Printf.sprintf "{\"source\":%s,\"output\":%s,\"source_items\":%d,\"translated_items\":%d,\"diagnostics\":[%s]}"
  (json_string r.source) (json_string r.relative) r.items (List.length r.segments)
  (String.concat "," (List.map diagnostic_json r.diagnostics))
let diagnose r loc code message = r.diagnostics <- r.diagnostics @ [{loc;code;message}]
let analyze checker partial source relative =
  let r={source;relative;items=0;segments=[];diagnostics=[]} in
  try
    let ast=let ic=open_in source in Fun.protect ~finally:(fun () -> close_in ic) (fun () ->
      let lex=Lexing.from_channel ic in Location.init lex source; Parse.implementation lex) in
    let r={r with items=List.length ast} in
    let env=ref (Compmisc.initial_env ()) and c=context () in
    List.iter (fun original ->
      let previous=snapshot c in
      try
        (* The compiler typechecks declarations but never evaluates them. Keep
           its environment even for unsupported declarations, to infer later
           independent values; the translation environment remains stricter. *)
        let typed,_,_,_,next=Typemod.type_structure !env [original] in
        env:=next;
        let text=String.concat "" (List.map (item c) typed.str_items) in
        if text<>"" then r.segments <- r.segments @ [{text;loc=original.pstr_loc}]
      with
      | Unsupported (loc,code,message) -> restore c previous; diagnose r loc code message
      | exn -> restore c previous; diagnose r original.pstr_loc "ocaml-type" (Format.asprintf "%a" Location.report_exception exn)) ast;
    if r.segments<>[] then with_temp (fun work ->
      let text segments=header ^ String.concat "\n" (List.map (fun s -> s.text) segments) in
      match check checker work (text r.segments) with
      | None -> ()
      | Some message when not partial -> r.segments<-[]; diagnose r Location.none "soma-check" message
      | Some _ ->
        let accepted=ref [] in
        List.iter (fun s -> match check checker work (text (!accepted @ [s])) with
          | None -> accepted:= !accepted @ [s]
          | Some message -> diagnose r s.loc "soma-check" message) r.segments;
        r.segments<- !accepted);
    r
  with exn ->
    let loc=match Location.error_of_exn exn with
      | Some (`Ok error) -> error.Location.main.Location.loc
      | _ -> Location.in_file source in
    diagnose r loc "ocaml-parse" (Format.asprintf "%a" Location.report_exception exn); r

let help = {|Usage: soma insert PATH [--out DIR] [--partial] [--report FILE] [--json]

Translate an OCaml .ml file or directory into editable, checked .soma files.
Uses OCaml's parser and type inference. Never evaluates the source or runs PPX.
Value bodies use ML expression blocks, including pure let/and and ML arrows.
Each output is checked with soma check before publication. Existing files are
never overwritten; source files are never edited. Directory inputs are scanned
recursively, ignoring symlinks, hidden directories, _build and duniverse.

  --out DIR, -o DIR   Output directory (PATH-soma by default).
  --partial          Keep independently translatable, checked declarations.
                     Reports omissions; still exits 1 if anything remains.
  --report FILE      Also write the JSON migration report to this new file.
  --json             Print the JSON report instead of human-readable progress.
  --report-only      Analyze and check fragments, without writing Soma files.
  -I DIR             Add an OCaml interface (.cmi) lookup directory; repeatable.
  -h, --help         Show this help.

Default mode writes no Soma files when any input has outstanding diagnostics.
Exit codes: 0 complete; 1 migration incomplete; 2 usage, destination or I/O error.
This first frontend uses OCaml 4.14 on a 64-bit host; -I interfaces must match.
The initial subset includes inferred polymorphic pure functions, 63-bit integer
arithmetic and signed comparisons, booleans, byte strings, lists/options/results,
immutable records/variants, matches and structurally checked list recursion.
Effects, mutable state, exceptions, foreign calls and unresolved dependencies
are reported for subsequent migration. A directory scan is a migration inventory,
not a claim that its modules have been linked into a complete translated program.
|}
let run () =
  pass_signals ();
  let input=ref None and output=ref None and report=ref None and checker=ref None in
  let partial=ref false and json=ref false and report_only=ref false and includes=ref [] in
  let rec args = function
    | [] -> ()
    | ("--help"|"-h")::_ -> print_string help; exit 0
    | ("--out"|"-o")::p::rest -> output:=Some p; args rest
    | "--report"::p::rest -> report:=Some p; args rest
    | "--checker"::p::rest -> checker:=Some p; args rest
    | "-I"::p::rest -> includes:= !includes @ [p]; args rest
    | "--partial"::rest -> partial:=true; args rest
    | "--json"::rest -> json:=true; args rest
    | "--report-only"::rest -> report_only:=true; args rest
    | s::_ when String.length s>0 && s.[0]='-' -> invalid_arg ("unknown or incomplete option " ^ s)
    | p::rest -> if !input<>None then invalid_arg "give one input file or directory"; input:=Some p; args rest in
  args (List.tl (Array.to_list Sys.argv));
  if Sys.int_size <> 63 then invalid_arg "the initial insertion frontend requires a 64-bit OCaml host";
  let input=match !input with Some p -> Unix.realpath p | None -> invalid_arg "no OCaml input given" in
  let checker=match !checker with Some p -> p | None -> invalid_arg "invoke this frontend through soma insert" in
  let out=match !output with Some p -> p | None -> input ^ "-soma" in
  let rec files root relative =
    let p=if relative="" then root else Filename.concat root relative in
    match (Unix.lstat p).Unix.st_kind with
    | Unix.S_REG when Filename.check_suffix p ".ml" -> [p,relative]
    | Unix.S_DIR -> Sys.readdir p |> Array.to_list |> List.sort String.compare |> List.concat_map (fun n ->
        if n="" || n.[0]='.' || List.mem n ["_build";"duniverse";"node_modules"] then [] else
        files root (if relative="" then n else Filename.concat relative n))
    | _ -> [] in
  let directory=Sys.is_directory input in
  let inputs=if directory then files input "" else
    if Filename.check_suffix input ".ml" then [input,Filename.basename input] else invalid_arg "input must be an OCaml .ml file or directory" in
  if inputs=[] then invalid_arg "no OCaml .ml files found";
  Clflags.include_dirs:= !includes;
  Compmisc.init_path ();
  ignore (Warnings.parse_options false "-a");
  let results=List.map (fun (file,rel) -> analyze checker !partial file (Filename.remove_extension rel ^ ".soma")) inputs in
  let incomplete=List.exists (fun r -> r.diagnostics<>[]) results in
  let publish=not !report_only && (!partial || not incomplete) in
  let outputs=if publish then List.filter (fun r -> r.segments<>[]) results else [] in
  let report_text="{\"version\":1,\"complete\":" ^ string_of_bool (not incomplete) ^
      ",\"files\":[" ^ String.concat "," (List.map result_json results) ^ "]}\n" in
  let destinations=List.map (fun r -> Filename.concat out r.relative) outputs @
    (if publish then [Filename.concat out "insert-report.json"] else []) @ (match !report with None->[]|Some p->[p]) in
  let seen=Hashtbl.create 16 in
  List.iter (fun p ->
    if Sys.file_exists p || Hashtbl.mem seen p then invalid_arg ("refusing to overwrite " ^ p);
    Hashtbl.add seen p ()) destinations;
  List.iter (fun r -> let p=Filename.concat out r.relative in mkdir (Filename.dirname p);
    write_new p (header ^ String.concat "\n" (List.map (fun s -> s.text) r.segments))) outputs;
  if publish then (mkdir out; write_new (Filename.concat out "insert-report.json") report_text);
  Option.iter (fun p -> mkdir (Filename.dirname p); write_new p report_text) !report;
  if !json then print_string report_text else begin
    List.iter (fun r ->
      Printf.printf "%s: %d/%d items translated and checked%s\n" r.source (List.length r.segments) r.items
        (if List.memq r outputs then " -> " ^ Filename.concat out r.relative else "");
      List.iter (fun (d : diagnostic) -> Printf.eprintf "%s:%d:%d: %s: %s\n" r.source d.loc.Location.loc_start.Lexing.pos_lnum
        (d.loc.loc_start.pos_cnum-d.loc.loc_start.pos_bol+1) d.code d.message) r.diagnostics) results
  end;
  exit (if incomplete then 1 else 0)
let main () = try run () with
  | Invalid_argument message | Sys_error message -> Printf.eprintf "soma insert: %s\n" message; exit 2
  | Unix.Unix_error (error,call,path) -> Printf.eprintf "soma insert: %s %s: %s\n" call path (Unix.error_message error); exit 2
