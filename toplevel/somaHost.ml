(* an answer's shapes: carried out, a boolean read, data *)
let ans_ok = (true, (0., []))
let ans_flag b = (b, (0., []))
let ans_data l = (true, (0., l))
let ans_found = function Some x -> ans_data [ x ] | None -> ans_flag false
(* not carried out, and why *)
let ans_why why = (false, (0., [ why ]))
let ans_exn e = ans_why (Printexc.to_string e)
(* one call on the host, its data, or its failure as not found with why *)
let attempt f = try ans_data (f ()) with e -> ans_exn e

(* ---------- the program's own, the clock, the log, its output ---------- *)

let clock () = (true, (Unix.gettimeofday (), []))
let log text = Printf.printf "%s %s\n%!" (string_of_float (Unix.gettimeofday ())) text; ans_ok
let local_time stamp =
  let tm = Unix.localtime (float_of_string stamp) in
  ans_data [ Printf.sprintf "%02d:%02d" tm.Unix.tm_hour tm.Unix.tm_min ]
let fail message = prerr_endline ("error: " ^ message); Stdlib.exit 1
let print text = print_string text; flush stdout; ans_ok
let exit code = Stdlib.exit (int_of_string code)
let cwd () = ans_data [ Sys.getcwd () ]
(* COUNT bytes of the system's randomness *)
