let path_stat f =
  ans_data
    (match Unix.lstat f with
     | st ->
         let kind = match st.st_kind with Unix.S_REG -> "file" | Unix.S_DIR -> "dir" | Unix.S_LNK -> "symlink" | _ -> "other" in
