(* Soma: the machine's host (theories/Soma/Host.v). A program built for the
   machine whose main uses Soma.Host gets [ml] as soma_host.ml, next to
   prog.ml and soma_bindings.ml (toplevel/somaOcaml.ml), which checks each
   of Host.v's declarations against it. It carries out what the program
   asks, with OCaml's unix library, and decides nothing. Every answer but
   argv's, print_lines', forever's and sock_select's is (carried out, or
   the boolean read, (a number, data)). *)

