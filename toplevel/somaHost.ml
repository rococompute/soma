let chmod p mode = ans_flag (try Unix.chmod p (int_of_string ("0o" ^ mode)); true with _ -> false)

(* appended in one write, then to disk: what was appended survives a crash
   whole *)
let append_synced p s =
  let fd = Unix.openfile p [ Unix.O_WRONLY; Unix.O_APPEND; Unix.O_CREAT ] 0o644 in
  Fun.protect ~finally:(fun () -> Unix.close fd) (fun () ->
      let b = Bytes.of_string s in
      if Unix.write fd b 0 (Bytes.length b) <> Bytes.length b then failwith (p ^ ": short write");
      Unix.fsync fd);
  ans_ok

(* one call on the host's files: carried out, or not and why *)
