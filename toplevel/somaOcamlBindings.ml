(* The declarations shared by Soma's native OCaml and MirageOS builds.
   This module does not depend on either backend: declarations are checked
   once, then both generate the same typed wrappers and extraction names. *)
open Names

let error msg = CErrors.user_err Pp.(str "OCaml: " ++ msg)

let main_reference () =
  try Nametab.locate (Libnames.qualid_of_ident (Id.of_string "main"))
  with Not_found -> error Pp.(str "the program defines no main, which is what OCaml runs.")

(* The constants [main] depends on, without a body: those of OCaml modules
   among them *)
let used_modules () =
  let modules = !SomaForeign.ocaml_modules () in
  if modules = [] then [] else
  match (try Some (Nametab.locate (Libnames.qualid_of_ident (Id.of_string "main"))) with Not_found -> None) with
  | None -> []
  | Some main ->
    let st = Conv_oracle.get_transp_state (Environ.oracle (Global.env ())) in
    let _, assums = Assumptions.assumptions (Library.indirect_accessor [@ocaml.alert "-deprecated"]) st [main] in
    let used = Printer.ContextObjectMap.fold (fun o _ acc -> match o with
        | Printer.Axiom (Printer.Constant k, _) -> Cset_env.add k acc
        | _ -> acc) assums Cset_env.empty in
    List.filter (fun (m : SomaForeign.ocaml_module) ->
        List.exists (fun (c, _, _) -> Cset_env.mem c used) m.items) modules

let header = "(* Generated by Soma (toplevel/somaOcamlBindings.ml). *)\n"

(* the type variables of an OCaml type, in order: ['s; 'a] *)
let type_variables ty =
  let n = String.length ty in
  let rec go i acc =
    if i >= n then List.rev acc
    else if ty.[i] = '\'' then
      let j = ref (i + 1) in
      while !j < n && (match ty.[!j] with 'a'..'z' | 'A'..'Z' | '0'..'9' | '_' -> true | _ -> false) do incr j done;
      let v = String.sub ty i (!j - i) in
      go !j (if List.mem v acc then acc else v :: acc)
    else go (i + 1) acc in
  go 0 []

(* A declaration's name in soma_bindings.ml: Async.Deferred.bind is
   async__Deferred__bind *)
let binding_name (m : SomaForeign.ocaml_module) path =
  String.uncapitalize_ascii m.top ^ "__" ^ String.concat "__" (String.split_on_char '.' path)

(* soma_bindings.ml: each value that the definitions declare, at its
   declared type, its type variables those of a polymorphic value, so that
   OCaml checks it. Each is applied to as many arguments as it is declared
   with: so a library's labels need not be declared (Deferred.bind's ~f,
   given in its place), and its optional arguments are left out, as OCaml
   allows of an application of all its arguments. *)
let bindings_ml modules =
  header ^ "(* Each value that a .definition declares, at its declared type. *)\n" ^
  String.concat "" (List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      let definition = match m.ml_file with
        | Some f -> Filename.remove_extension (Filename.basename f) ^ ".definition"
        | None -> String.uncapitalize_ascii m.top ^ ".definition" in
      List.filter_map (fun (_, path, item) -> match item with
          | SomaForeign.OCamlType _ -> None
          | SomaForeign.OCamlValue (ty, labels) ->
            let vars = type_variables ty in
            let poly = if vars = [] then "" else String.concat " " vars ^ ". " in
            let args = List.mapi (fun i _ -> Printf.sprintf "a%d" i) labels in
            (* a named argument is given by its label: ~attrs:a1 *)
            let given = List.map2 (fun a l -> match l with
                | Some l -> Printf.sprintf "~%s:%s" l a
                | None -> a) args labels in
            let value = m.top ^ "." ^ path in
            let body = if args = [] then value
              else Printf.sprintf "fun %s -> %s %s" (String.concat " " args) value (String.concat " " given) in
            Some (Printf.sprintf "\n(* %s: %s *)\nlet %s : %s%s =\n  %s\n"
                    definition path (binding_name m path) poly ty body))
        m.items) modules)

(* soma_nat.ml: nat as extraction makes it in prog.ml, OCaml's int (as in
   an image: ExtrOcamlNatInt), named for a declared type's nat *)
let soma_nat_ml =
  header ^ "(* Soma's nat, as extracted: OCaml's int, never below 0. *)\n\
            type nat = int\n"


let extraction_lines modules =
  List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      List.map (fun (c, path, item) ->
          let soma = Libnames.string_of_path (Nametab.path_of_global (GlobRef.ConstRef c)) in
          match item with
          | SomaForeign.OCamlValue _ ->
            Printf.sprintf "Extract Constant %s => \"Soma_bindings.%s\".\n" soma (binding_name m path)
          | SomaForeign.OCamlType n ->
            let ps = List.init n (fun i -> "'" ^ String.make 1 (Char.chr (Char.code 'a' + i))) in
            let applied = match ps with
              | [] -> "" | [p] -> p ^ " " | ps -> "(" ^ String.concat ", " ps ^ ") " in
            Printf.sprintf "Extract Constant %s %s => \"%s%s.%s\".\n" soma
              (String.concat " " (List.map (Printf.sprintf "%S") ps)) applied m.top path)
        m.items) modules

let checked_modules ?(reserved = []) () =
  let modules = used_modules () in
  ignore (main_reference ());
  (* Generated filenames must stay distinct on case-insensitive filesystems,
     and an own module must not shadow a library top used by another binding.
     Apostrophes are legal OCaml identifiers and remain supported. *)
  let same_name a b = String.equal (String.lowercase_ascii a) (String.lowercase_ascii b) in
  let names = List.filter_map (fun (m : SomaForeign.ocaml_module) ->
      Option.map (fun _ -> m.top) m.ml_file) modules in
  List.iter (fun n ->
      if List.length (List.filter (same_name n) names) > 1 then
        CErrors.user_err Pp.(str "the program uses two OCaml modules named " ++ str n ++ str ".");
      if List.exists (fun (m : SomaForeign.ocaml_module) -> m.ml_file = None && same_name n m.top) modules then
        CErrors.user_err Pp.(str "the OCaml module " ++ str n ++
          str " shadows a library module used by the program.");
      if List.exists (same_name n) (["Prog"; "Soma_main"; "Soma_bindings"; "Soma_nat"; "Soma_host"; "Soma_word64"; "Soma_handles"; "Soma_effect"; "Float64"; "Uint63"] @ reserved) then
        CErrors.user_err Pp.(str "an OCaml module cannot be named " ++ str n ++ str ", the name of one Soma makes."))
    names;
  modules, List.sort_uniq compare ((if SomaNative.loaded () then ["lwt"] else []) @
    List.concat_map (fun (m : SomaForeign.ocaml_module) -> m.libraries) modules)

(* whether a module is FILE.c (vernac/somaC.ml), and its files: the
   OCaml module of externals, FILE.soma.h, the stubs, and FILE.c itself,
   under another name than the OCaml module's, which dune would give the
   same object file *)
let is_c (m : SomaForeign.ocaml_module) =
  match m.ml_file with Some f -> Filename.check_suffix f ".c" | None -> false

let c_files ~read_file (m : SomaForeign.ocaml_module) =
  match m.ml_file with
  | None -> []
  | Some c ->
    let file = String.uncapitalize_ascii m.top in
    let definition = SomaC.base_of c ^ ".definition" in
    let types = List.filter_map (fun (_, path, item) -> match item with
        | SomaForeign.OCamlType _ -> Some path | _ -> None) m.items in
    let values = List.filter_map (fun (_, path, item) -> match item with
        | SomaForeign.OCamlValue (ty, labels) ->
          (match SomaC.signature ~top:m.top ty with
           | Ok s -> Some ((path, s), (path, labels))
           | Error why -> error Pp.(str definition ++ str ": " ++ str path ++ str ": " ++ str why))
        | _ -> None) m.items in
    let sigs = List.map fst values and labels = List.map snd values in
    [file ^ ".ml", SomaC.module_ml ~file ~types ~labels sigs;
     file ^ ".soma.h", SomaC.header_h ~file ~definition sigs;
     file ^ "_soma_stubs.c", SomaC.stubs_c ~file sigs;
     file ^ "_soma_c.c", Printf.sprintf "#line 1 %S\n" c ^ read_file c]

(* the C files' names, for dune's foreign_stubs *)
let c_stub_names made =
  List.filter_map (fun f ->
      if Filename.check_suffix f ".c" then Some (Filename.remove_extension f) else None) made

(* The program's modules; a C module's files go to [c_file], which is
   [file] unless an image keeps them in a library of their own, and are
   then not among those returned *)
let write_files ~file ?c_file ~read_file ~directives modules =
  file "soma_nat.ml" soma_nat_ml;
  file "soma_bindings.ml" (bindings_ml modules);
  ["soma_nat.ml"; "soma_bindings.ml"] @
  List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      if is_c m then begin
        let files = c_files ~read_file m in
        match c_file with
        | Some write -> List.iter (fun (f, text) -> write f text) files; []
        | None -> List.iter (fun (f, text) -> file f text) files; List.map fst files
      end else
      match m.ml_file with
      | None -> []
      | Some ml ->
        let f = String.uncapitalize_ascii m.top ^ ".ml" in
        file f ((if directives then Printf.sprintf "# 1 %S\n" ml else "") ^ read_file ml);
        [f]) modules

(* lwt.unix is a library of the opam package lwt *)
let package_of library = match String.index_opt library '.' with
  | Some i -> String.sub library 0 i
  | None -> library

(* the libraries that come with the compiler, which no opam package has:
   a definition may name them (OCaml Library "unix") like any other *)
let with_compiler = ["unix"; "str"; "threads"; "dynlink"; "bigarray"; "compiler-libs"; "runtime_events"; "ocamldoc"]

(* the opam packages that [libraries] are in *)
let packages_of libraries =
  List.sort_uniq compare
    (List.filter (fun p -> not (List.mem p with_compiler)) (List.map package_of libraries))
