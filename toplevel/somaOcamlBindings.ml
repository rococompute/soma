(* The declarations shared by Soma's native OCaml and MirageOS builds.
   This module does not depend on either backend: declarations are checked
   once, then both generate the same typed wrappers and extraction names. *)
open Names

let error msg = CErrors.user_err Pp.(str "OCaml: " ++ msg)

let main_reference () =
  try Nametab.locate (Libnames.qualid_of_ident (Id.of_string "main"))
  with Not_found -> error Pp.(str "the program defines no main, which is what OCaml runs.")

(* The constants [main] depends on, without a body: those of OCaml modules
   among them *)
let used_modules () =
  let modules = !SomaForeign.ocaml_modules () in
  if modules = [] then [] else
  match (try Some (Nametab.locate (Libnames.qualid_of_ident (Id.of_string "main"))) with Not_found -> None) with
  | None -> []
  | Some main ->
    (* Defined descriptors have no assumptions. Follow checked bodies and types,
       including opaque proofs, rather than treating the assumption set as the
       dependency graph. No imported native body is ever executed here. *)
    let env = Global.env () in
    let used = ref Cset_env.empty in
    let minds = Hashtbl.create 37 in
    let rec visit term =
      (match Constr.kind term with
       | Constr.Const(c,_) when not(Cset_env.mem c !used) ->
         used := Cset_env.add c !used;
         let cb = Environ.lookup_constant c env in
         visit cb.Declarations.const_type;
         (match cb.Declarations.const_body with
          | Declarations.Def body -> visit body
          | Declarations.OpaqueDef opaque ->
            let body,_ = try Global.force_proof (Library.indirect_accessor [@ocaml.alert "-deprecated"]) opaque
              with e when CErrors.noncritical e ->
                error Pp.(str "cannot read opaque dependency " ++
                  str (KerName.to_string(Constant.canonical c)) ++
                  str " while collecting native bindings: " ++ CErrors.print_no_report e) in
            visit body
          | _ -> ())
       | Constr.Ind((m,_),_) | Constr.Construct(((m,_),_),_) -> visit_mind m
       | Constr.Proj(p,_,_) -> visit_mind(fst(Projection.inductive p))
       | _ -> ());
      Constr.iter visit term
    and visit_mind m =
      let key=KerName.to_string(MutInd.canonical m) in
      if not(Hashtbl.mem minds key)then begin
        Hashtbl.add minds key ();
        let mb=Environ.lookup_mind m env in
        Array.iter(fun(p:Declarations.one_inductive_body)->visit p.mind_user_arity;
          Array.iter visit p.mind_user_lc)mb.mind_packets
      end in
    (match main with GlobRef.ConstRef c -> visit (Constr.mkConstU (c,UVars.Instance.empty)) | _ -> ());
    (* We emit every declaration of a selected module. Collect every emitted
       declaration's checked dependencies too, including unused owned schemas. *)
    let rec expand pending selected =
      let newly_used,remaining=List.partition(fun(m:SomaForeign.ocaml_module)->
        List.exists(fun(c,_,_)->Cset_env.mem c !used)m.items)pending in
      match newly_used with
      | [] -> List.rev selected
      | _ ->
        List.iter(fun(m:SomaForeign.ocaml_module)->List.iter(fun(c,_,_)->
          visit(Constr.mkConstU(c,UVars.Instance.empty)))m.items)newly_used;
        expand remaining(List.rev_append newly_used selected) in
    expand modules []

(* Libraries composed into one application may give their generated bindings
   distinct names. This changes only artifact names, never a native signature. *)
let bindings_module () =
  match Sys.getenv_opt "SOMA_OCAML_BINDINGS_MODULE" with
  | None -> "Soma_bindings"
  | Some name ->
    if name="" || not(match name.[0]with 'A'..'Z'->true|_->false) ||
       not(String.for_all(function 'a'..'z'|'A'..'Z'|'0'..'9'|'_'|'\''->true|_->false)name)
    then error Pp.(str "SOMA_OCAML_BINDINGS_MODULE must be a single OCaml module identifier");
    name
let bindings_filename () = String.uncapitalize_ascii(bindings_module()) ^ ".ml"

let header = "(* Generated by Soma (toplevel/somaOcamlBindings.ml). *)\n"

(* the type variables of an OCaml type, in order: ['s; 'a] *)
let type_variables ty =
  let n = String.length ty in
  let rec go i acc =
    if i >= n then List.rev acc
    else if ty.[i] = '\'' then
      let j = ref (i + 1) in
      while !j < n && (match ty.[!j] with 'a'..'z' | 'A'..'Z' | '0'..'9' | '_' -> true | _ -> false) do incr j done;
      let v = String.sub ty i (!j - i) in
      go !j (if List.mem v acc then acc else v :: acc)
    else go (i + 1) acc in
  go 0 []

(* A declaration's name in soma_bindings.ml: Async.Deferred.bind is
   async__Deferred__bind *)
let binding_name (m : SomaForeign.ocaml_module) path =
  String.uncapitalize_ascii m.top ^ "__" ^ String.concat "__" (String.split_on_char '.' path)

(* Native descriptors use an injective encoding of the semantic pair. The
   legacy dot-to-underscore spelling collides for A__B.x and A.B.x. Hex
   contains no underscore, so this separator also distinguishes tuple parts. *)
let native_binding_name (n:SomaForeign.native_callback) =
  let hex text = String.concat "" (List.init(String.length text)
    (fun i->Printf.sprintf "%02x" (Char.code text.[i]))) in
  "soma_native_" ^ hex n.namespace ^ "_" ^ hex n.name

let owned_records modules = List.concat_map(fun(m:SomaForeign.ocaml_module)->
  List.filter_map(fun(c,_,item)->match item with
    | SomaForeign.OCamlNativeOwnedRecord r -> Some(c,r)
    | _->None)m.items)modules

let owned_variants modules = List.concat_map(fun(m:SomaForeign.ocaml_module)->
  List.filter_map(fun(c,_,item)->match item with
    | SomaForeign.OCamlNativeOwnedVariant v -> Some(c,v)
    | _->None)m.items)modules

let owned_callables modules = List.concat_map(fun(m:SomaForeign.ocaml_module)->
  List.filter_map(fun(c,_,item)->match item with
    | SomaForeign.OCamlNativeCallableType info->Some(c,info)|_->None)m.items)modules

let rec native_product = function
  | [] -> "unit" | [value] -> value
  | first::rest -> "(" ^ first ^ " * " ^ native_product rest ^ ")"
let rec native_pattern = function
  | [] -> "()" | [value] -> value
  | first::rest -> "(" ^ first ^ ", " ^ native_pattern rest ^ ")"
let native_binding (m:SomaForeign.ocaml_module) (n:SomaForeign.native_callback) =
  let args = List.mapi(fun i _->"a"^string_of_int i)n.arguments in
  let signature = native_product(List.map(fun t->"("^t^")")n.arguments)^" -> ("^n.result^")" in
  let record_prefix ty = try String.sub ty 0 (String.rindex ty '.') with Not_found ->
    error Pp.(str "a native record needs a declared native type") in
  let field prefix name = prefix ^ "." ^ name in
  let assignments prefix names values = String.concat "; " (List.map2(fun n a->field prefix n^" = "^a)names values) in
  let body = match n.operation,args with
    | SomaForeign.NativeValue path,_ ->
      let given=List.map2(fun a->function None->a|Some l->"~"^l^":"^a)args n.labels in
      m.top^"."^path^" "^String.concat " "given
    | SomaForeign.NativeExternalValue path,_ ->
      let given=List.map2(fun a->function None->a|Some l->"~"^l^":"^a)args n.labels in
      path^" "^String.concat " "given
    | SomaForeign.NativeGet name,[record] -> record^"."^field(record_prefix(List.hd n.arguments))name
    | SomaForeign.NativeSet name,[record;value] -> record^"."^field(record_prefix(List.hd n.arguments))name^" <- "^value
    | SomaForeign.NativeBuild names,_ ->
      "({ "^assignments(record_prefix n.result)names args^" } : "^n.result^")"
    | SomaForeign.NativeCopy names,record::values ->
      "{ "^record^" with "^assignments(record_prefix(List.hd n.arguments))names values^" }"
    | SomaForeign.NativeCallableApply(Some c),body::values ->
      let given=List.map2(fun value label->match label with None->value|Some label->"~"^label^":"^value)values c.callable_labels in
      body ^ " " ^ String.concat " "given
    | SomaForeign.NativeVariantView(Some v),[value] ->
      let rec branches depth=function
        | []->assert false
        | c::rest ->
          let payload=match c.SomaForeign.case_payload with None->"()"|Some _->"payload"in
          let answer=if rest=[]then payload else "Stdlib.Ok ("^payload^")"in
          let rec wrap n s=if n=0 then s else wrap(n-1)("Stdlib.Error ("^s^")")in
          let pattern="`"^c.case_tag^(match c.case_payload with None->""|Some _->" payload")in
          ("| "^pattern^" -> "^wrap depth answer)::(if rest=[]then[]else branches(depth+1)rest)in
      "match "^value^" with "^String.concat " "(branches 0 v.variant_cases)
    | SomaForeign.NativeVariantBuild(tag,Some v),[value] ->
      let c=List.find(fun c->c.SomaForeign.case_tag=tag)v.variant_cases in
      "`"^tag^(match c.case_payload with None->""|Some _->" "^value)
    | _ -> error Pp.(str "invalid native record callback metadata") in
  signature,"fun "^native_pattern args^" -> "^body

(* soma_bindings.ml: each value that the definitions declare, at its
   declared type, its type variables those of a polymorphic value, so that
   OCaml checks it. Each is applied to as many arguments as it is declared
   with: so a library's labels need not be declared (Deferred.bind's ~f,
   given in its place), and its optional arguments are left out, as OCaml
   allows of an application of all its arguments. *)
let bindings_ml modules =
  header ^ "(* Each value that a .definition declares, at its declared type. *)\n" ^
  String.concat "" (List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      let definition = match m.ml_file with
        | Some f -> Filename.remove_extension (Filename.basename f) ^ ".definition"
        | None -> String.uncapitalize_ascii m.top ^ ".definition" in
      List.filter_map (fun (_, path, item) -> match item with
          | SomaForeign.OCamlType _ | SomaForeign.OCamlNativeType _ | SomaForeign.OCamlNativeOwnedRecord _ | SomaForeign.OCamlNativeOwnedVariant _ | SomaForeign.OCamlNativeCallableType _ -> None
          | SomaForeign.OCamlNativeCallback n ->
            let signature,body=native_binding m n in
            Some(Printf.sprintf "\n(* native %s.%s *)\nlet %s : %s =\n  %s\n"
              n.namespace n.name (native_binding_name n) signature body)
          | SomaForeign.OCamlValue (ty, labels) ->
            let vars = type_variables ty in
            let poly = if vars = [] then "" else String.concat " " vars ^ ". " in
            let args = List.mapi (fun i _ -> Printf.sprintf "a%d" i) labels in
            (* a named argument is given by its label: ~attrs:a1 *)
            let given = List.map2 (fun a l -> match l with
                | Some l -> Printf.sprintf "~%s:%s" l a
                | None -> a) args labels in
            let value = m.top ^ "." ^ path in
            let body = if args = [] then value
              else Printf.sprintf "fun %s -> %s %s" (String.concat " " args) value (String.concat " " given) in
            Some (Printf.sprintf "\n(* %s: %s *)\nlet %s : %s%s =\n  %s\n"
                    definition path (binding_name m path) poly ty body))
        m.items) modules)

(* soma_nat.ml: nat as extraction makes it in prog.ml, OCaml's int (as in
   an image: ExtrOcamlNatInt), named for a declared type's nat *)
let soma_nat_ml =
  header ^ "(* Soma's nat, as extracted: OCaml's int, never below 0. *)\n\
            type nat = int\n"


let extraction_lines modules =
  List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      List.map (fun (c, path, item) ->
          let soma = Libnames.string_of_path (Nametab.path_of_global (GlobRef.ConstRef c)) in
          match item with
          | SomaForeign.OCamlNativeCallableType c ->
            Printf.sprintf "Extract Constant %s => %S.\n" soma (SomaForeign.native_callable_type c)
          | SomaForeign.OCamlNativeOwnedVariant v ->
            Printf.sprintf "Extract Constant %s => %S.\n" soma (SomaForeign.native_variant_type v)
          | SomaForeign.OCamlNativeOwnedRecord r ->
            Printf.sprintf "Extract Constant %s => %S.\n" soma (SomaForeign.native_record_type r)
          | SomaForeign.OCamlNativeType target ->
            Printf.sprintf "Extract Constant %s => %S.\n" soma target
          | SomaForeign.OCamlNativeCallback n ->
            Printf.sprintf "Extract Constant %s => %S.\n" soma (bindings_module()^"."^native_binding_name n)
          | SomaForeign.OCamlValue _ ->
            Printf.sprintf "Extract Constant %s => %S.\n" soma (bindings_module()^"."^binding_name m path)
          | SomaForeign.OCamlType n ->
            let ps = List.init n (fun i -> "'" ^ String.make 1 (Char.chr (Char.code 'a' + i))) in
            let applied = match ps with
              | [] -> "" | [p] -> p ^ " " | ps -> "(" ^ String.concat ", " ps ^ ") " in
            Printf.sprintf "Extract Constant %s %s => \"%s%s.%s\".\n" soma
              (String.concat " " (List.map (Printf.sprintf "%S") ps)) applied m.top path)
        m.items) modules

(* Hashes bound filesystem names, never logical identity. Refuse a collision
   between canonical declarations before emitting or overwriting a module. *)
let check_owned_module_names entries =
  let emitted=Hashtbl.create 17 in
  List.iter(fun(module_name,canonical)->
    let key=String.lowercase_ascii module_name in
    match Hashtbl.find_opt emitted key with
    | Some previous when previous<>canonical ->
      error Pp.(str "owned record emitted-name collision for "++str module_name)
    | Some _->()
    | None->Hashtbl.add emitted key canonical)entries

let checked_modules ?(reserved = []) () =
  let modules = used_modules () in
  ignore (main_reference ());
  (* Generated filenames must stay distinct on case-insensitive filesystems,
     and an own module must not shadow a library top used by another binding.
     Apostrophes are legal OCaml identifiers and remain supported. *)
  let same_name a b = String.equal (String.lowercase_ascii a) (String.lowercase_ascii b) in
  let owned_names=List.map(fun(_,r)->SomaForeign.native_record_module r,
    (r.SomaForeign.record_namespace,r.record_name))(owned_records modules) @
    List.map(fun(_,v)->SomaForeign.native_variant_module v,
      (v.SomaForeign.variant_namespace,v.variant_name))(owned_variants modules) @
    List.map(fun(_,c)->SomaForeign.native_callable_module c,
      (c.SomaForeign.callable_namespace,c.callable_name))(owned_callables modules)in
  check_owned_module_names owned_names;
  let generated=List.map fst owned_names in
  if List.exists(fun(m:SomaForeign.ocaml_module)->same_name(bindings_module())m.top)modules then
    error Pp.(str "generated bindings module collides with a caller or library module");
  if List.exists(same_name(bindings_module())) (["Prog";"Soma_main";"Soma_nat";"Soma_host";"Soma_word64";"Soma_handles";"Soma_effect";"Float64";"Uint63"] @ generated @ reserved) then
    error Pp.(str "generated bindings module collides with a native or reserved module");
  List.iter(fun name->
    if List.exists(fun(m:SomaForeign.ocaml_module)->same_name name m.top)modules ||
       List.exists(same_name name)reserved then
      error Pp.(str "owned record module "++str name++str " collides with a caller, native or reserved module"))generated;
  let names = List.filter_map (fun (m : SomaForeign.ocaml_module) ->
      Option.map (fun _ -> m.top) m.ml_file) modules in
  List.iter (fun n ->
      if List.length (List.filter (same_name n) names) > 1 then
        CErrors.user_err Pp.(str "the program uses two OCaml modules named " ++ str n ++ str ".");
      if List.exists (fun (m : SomaForeign.ocaml_module) -> m.ml_file = None && same_name n m.top) modules then
        CErrors.user_err Pp.(str "the OCaml module " ++ str n ++
          str " shadows a library module used by the program.");
      if List.exists (same_name n) (["Prog"; "Soma_main"; bindings_module(); "Soma_bindings"; "Soma_nat"; "Soma_host"; "Soma_word64"; "Soma_handles"; "Soma_effect"; "Float64"; "Uint63"] @ reserved) then
        CErrors.user_err Pp.(str "an OCaml module cannot be named " ++ str n ++ str ", the name of one Soma makes."))
    names;
  modules, List.sort_uniq compare ((if SomaNative.loaded () then ["lwt"] else []) @
    List.concat_map (fun (m : SomaForeign.ocaml_module) -> m.libraries) modules)

(* whether a module is FILE.c (vernac/somaC.ml), and its files: the
   OCaml module of externals, FILE.soma.h, the stubs, and FILE.c itself,
   under another name than the OCaml module's, which dune would give the
   same object file *)
let is_c (m : SomaForeign.ocaml_module) =
  match m.ml_file with Some f -> Filename.check_suffix f ".c" | None -> false

let c_files ~read_file (m : SomaForeign.ocaml_module) =
  match m.ml_file with
  | None -> []
  | Some c ->
    let file = String.uncapitalize_ascii m.top in
    let definition = SomaC.base_of c ^ ".definition" in
    let types = List.filter_map (fun (_, path, item) -> match item with
        | SomaForeign.OCamlType _ -> Some path | _ -> None) m.items in
    let values = List.filter_map (fun (_, path, item) -> match item with
        | SomaForeign.OCamlValue (ty, labels) ->
          (match SomaC.signature ~top:m.top ty with
           | Ok s -> Some ((path, s), (path, labels))
           | Error why -> error Pp.(str definition ++ str ": " ++ str path ++ str ": " ++ str why))
        | _ -> None) m.items in
    let sigs = List.map fst values and labels = List.map snd values in
    [file ^ ".ml", SomaC.module_ml ~file ~types ~labels sigs;
     file ^ ".soma.h", SomaC.header_h ~file ~definition sigs;
     file ^ "_soma_stubs.c", SomaC.stubs_c ~file sigs;
     file ^ "_soma_c.c", Printf.sprintf "#line 1 %S\n" c ^ read_file c]

(* the C files' names, for dune's foreign_stubs *)
let c_stub_names made =
  List.filter_map (fun f ->
      if Filename.check_suffix f ".c" then Some (Filename.remove_extension f) else None) made

(* The program's modules; a C module's files go to [c_file], which is
   [file] unless an image keeps them in a library of their own, and are
   then not among those returned *)
let write_files ~file ?c_file ~read_file ~directives modules =
  file "soma_nat.ml" soma_nat_ml;
  file (bindings_filename()) (bindings_ml modules);
  let owned=owned_records modules in
  let owned_entries=List.map(fun(c,r)->
    let filename=SomaForeign.native_record_filename r in
    let contents=SomaForeign.native_record_ml r in
    file filename contents;
    let symbol=Libnames.string_of_path(Nametab.path_of_global(GlobRef.ConstRef c))in
    let source=SomaImport.resolve_project_file r.SomaForeign.record_source in
    Printf.sprintf "%S %S %S %S %S\n" symbol r.record_source
      (SomaMerkle.string(read_file source))filename(SomaMerkle.string contents))owned in
  file "native_owned.manifest" ("soma-native-owned-v1\n"^String.concat ""(List.sort String.compare owned_entries));
  let variants=owned_variants modules in
  let variant_entries=List.map(fun(c,v)->
    let filename=SomaForeign.native_variant_filename v in
    let contents=SomaForeign.native_variant_ml v in
    file filename contents;
    let symbol=Libnames.string_of_path(Nametab.path_of_global(GlobRef.ConstRef c))in
    Printf.sprintf "%S %S %S %S %S\n" symbol v.variant_source
      (SomaMerkle.string(read_file(SomaImport.resolve_project_file v.variant_source)))
      filename(SomaMerkle.string contents))variants in
  file "native_variants.manifest" ("soma-native-variants-v1\n"^String.concat ""(List.sort String.compare variant_entries));
  let callables=owned_callables modules in
  let callable_entries=List.map(fun(c,info)->
    let filename=SomaForeign.native_callable_filename info in
    let contents=SomaForeign.native_callable_ml info in
    file filename contents;
    let symbol=Libnames.string_of_path(Nametab.path_of_global(GlobRef.ConstRef c))in
    Printf.sprintf "%S %S %S %S %S\n" symbol info.callable_source
      (SomaMerkle.string(read_file(SomaImport.resolve_project_file info.callable_source)))
      filename(SomaMerkle.string contents))callables in
  file "native_callables.manifest" ("soma-native-callables-v1\n"^String.concat ""(List.sort String.compare callable_entries));
  let entries = List.concat_map(fun (m:SomaForeign.ocaml_module)->
    List.filter_map(fun(c,path,item)->match item with
      | SomaForeign.OCamlNativeType _ | SomaForeign.OCamlNativeOwnedRecord _ | SomaForeign.OCamlNativeOwnedVariant _ | SomaForeign.OCamlNativeCallableType _ | SomaForeign.OCamlNativeCallback _ ->
        let symbol=Libnames.string_of_path(Nametab.path_of_global(GlobRef.ConstRef c)) in
        let source=match item with
          | SomaForeign.OCamlNativeOwnedRecord r -> SomaMerkle.string(read_file(SomaImport.resolve_project_file r.record_source))
          | SomaForeign.OCamlNativeOwnedVariant v -> SomaMerkle.string(read_file(SomaImport.resolve_project_file v.variant_source))
          | SomaForeign.OCamlNativeCallableType c -> SomaMerkle.string(read_file(SomaImport.resolve_project_file c.callable_source))
          | _->(match m.ml_file with None->"library"|Some f->SomaMerkle.file_hash f)in
        Some(Printf.sprintf "%S %S %S %S\n" symbol m.top source (SomaForeign.native_identity item))
      | _->None)m.items)modules in
  file "native_abi.manifest" ("soma-native-abi-v1\n"^String.concat ""(List.sort String.compare entries));
  ["soma_nat.ml"; bindings_filename()] @ List.map(fun(_,r)->SomaForeign.native_record_filename r)owned @
  List.map(fun(_,v)->SomaForeign.native_variant_filename v)variants @
  List.map(fun(_,c)->SomaForeign.native_callable_filename c)callables @
  List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      if is_c m then begin
        let files = c_files ~read_file m in
        match c_file with
        | Some write -> List.iter (fun (f, text) -> write f text) files; []
        | None -> List.iter (fun (f, text) -> file f text) files; List.map fst files
      end else
      match m.ml_file with
      | None -> []
      | Some ml ->
        let f = String.uncapitalize_ascii m.top ^ ".ml" in
        file f ((if directives then Printf.sprintf "# 1 %S\n" ml else "") ^ read_file ml);
        [f]) modules

(* lwt.unix is a library of the opam package lwt *)
let package_of library = match String.index_opt library '.' with
  | Some i -> String.sub library 0 i
  | None -> library

(* the libraries that come with the compiler, which no opam package has:
   a definition may name them (OCaml Library "unix") like any other *)
let with_compiler = ["unix"; "str"; "threads"; "dynlink"; "bigarray"; "compiler-libs"; "runtime_events"; "ocamldoc"]

(* the opam packages that [libraries] are in *)
let packages_of libraries =
  List.sort_uniq compare
    (List.filter (fun p -> not (List.mem p with_compiler)) (List.map package_of libraries))
