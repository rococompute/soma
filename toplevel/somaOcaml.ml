let dune_file ~js libraries =
  let ppx, libs = List.partition (fun l -> String.starts_with ~prefix:"ppx_" l) libraries in
  Printf.sprintf
    ";; Generated by Soma (toplevel/somaOcaml.ml).\n\
     (executable\n (name soma_main)\n (modes %s)\n (libraries %s)\n%s\
    \ (flags (:standard -w -a)))\n"
    (if js then "js" else "exe") (String.concat " " libs)
    (if ppx = [] then "" else Printf.sprintf " (preprocess (pps %s))\n" (String.concat " " ppx))

(* the modules main uses, checked, and the libraries they use *)
let checked_modules = SomaOcamlBindings.checked_modules

(* The OCaml project of the program, in [dir]: [main] extracted, the
   bindings, the project's modules (with line directives to them when
   [~directives], so that OCaml's errors are about the files themselves),
   what runs [main], and dune's files *)
let write_project ~state ~modules ~libraries ~js ~directives dir =
  mkdir_p dir;
  extract ~state ~modules dir;
  let file f contents = ignore (update_file (Filename.concat dir f) contents) in
  file "dune" (dune_file ~js libraries);
  file "soma_main.ml" (entry_ml ());
  file "float64.ml" SomaMirage.float64_ml;
  file "uint63.ml" SomaMirage.uint63_ml;
  (* Soma.Host's primitives are Soma's own module *)
  let host = List.exists (fun (m : SomaForeign.ocaml_module) -> m.ml_file = None && m.top = host_module) modules in
  if host then file "soma_host.ml" SomaHost.ml;
  let own = SomaOcamlBindings.write_files ~file ~read_file ~directives modules in
  (* a module an earlier build of the program had, and this one has not,
     would be built with it: dune builds every module of the directory *)
  let made = ["prog.ml"; "prog.mli"; "soma_main.ml"; "float64.ml"; "uint63.ml"; "soma_nat.ml"; "soma_bindings.ml"]
             @ (if host then ["soma_host.ml"] else []) @ own in
  Array.iter (fun f ->
      if (Filename.check_suffix f ".ml" || Filename.check_suffix f ".mli") && not (List.mem f made) then
        (try Sys.remove (Filename.concat dir f) with Sys_error _ -> ()))
    (Sys.readdir dir)

