let dune_file ~js ~host ?(c = []) ~modules libraries =
  let ppx, libs = List.partition (fun l -> String.starts_with ~prefix:"ppx_" l) libraries in
  let stubs = (if host then ["soma_host_io"] else []) @ c in
  Printf.sprintf
    ";; Generated by Soma (toplevel/somaOcaml.ml).\n\
     (executable\n (name soma_main)\n (modes %s)\n (modules %s)\n (libraries %s)\n%s%s\
    \ (flags (:standard -w -a)))\n"
    (if js then "js" else "exe")
    (String.concat " " (List.map (Printf.sprintf "%S") modules)) (String.concat " " libs)
    (if ppx = [] then "" else Printf.sprintf " (preprocess (pps %s))\n" (String.concat " " ppx))
    (if stubs = [] then "" else Printf.sprintf " (foreign_stubs (language c) (names %s))\n" (String.concat " " stubs))

