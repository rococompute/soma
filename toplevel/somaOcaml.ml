let extract_marker = "; Generated by Soma (toplevel/somaOcaml.ml): soma extract"

(* an opam package's name: letters, digits, - and _ *)
let package_name name =
  let s = String.map (function 'a'..'z' | 'A'..'Z' | '0'..'9' | '-' | '_' as c -> c | _ -> '-') name in
  if s = "" || not (match s.[0] with 'a'..'z' | 'A'..'Z' -> true | _ -> false) then "soma-" ^ s else s

