(* A directory can outlive a build and contain files the user added or edited.
   Only remove an obsolete generated file whose receipt still matches; dune's
   explicit module list keeps all other files out of this executable. *)
let record_generated_files ~capture_generated dir made expected =
  let manifest = Filename.concat dir ".soma-ocaml-files" in
  let is_source f = Filename.basename f = f &&
    (List.mem f ["native_algebraic.manifest";"native_assemblies.manifest";"native_source_type_reexports.manifest";"native_static_data.manifest";"native_binding_initializers.manifest";"native_value_reexports.manifest"] ||
     List.exists (Filename.check_suffix f) [".ml"; ".mli"; ".c"; ".h";".assembly";".assembly-interface"] ||
     ((String.starts_with ~prefix:"soma_source_types_" f || String.starts_with ~prefix:"soma_values_" f) && Filename.check_suffix f ".exports")) in
  let hash f =
    let file = Filename.concat dir f in
    match Unix.lstat file with
    | { Unix.st_kind = Unix.S_REG; _ } -> Some (SomaMerkle.file_hash file)
    | _ -> None
    | exception (Unix.Unix_error _ | Sys_error _) -> None in
  List.iter (fun line -> match String.split_on_char ' ' line with
      | [f; digest] when is_source f && SomaMerkle.valid_hash digest && not (List.mem f made) ->
        if hash f = Some digest then
          (try Sys.remove (Filename.concat dir f) with Sys_error _ -> ())
      | _ -> ()) (read_lines manifest);
  let contents = String.concat "" (List.filter_map (fun f ->
      match Hashtbl.find_opt expected f, hash f with
      | Some expected, Some digest when String.equal expected digest -> Some (f ^ " " ^ digest ^ "\n")
      | _ -> None) made) in
  capture_generated ".soma-ocaml-files" contents;
  let tmp, oc = Filename.open_temp_file ~temp_dir:dir ".soma-ocaml-files-" ".tmp" in
  Fun.protect ~finally:(fun () ->
      close_out_noerr oc;
      try Sys.remove tmp with Sys_error _ -> ()) (fun () ->
      output_string oc contents;
      close_out oc;
      Sys.rename tmp manifest)

(* The OCaml project of the program, in [dir]: [main] extracted, the
   bindings, the project's modules (with line directives to them when
   [~directives], so that OCaml's errors are about the files themselves),
   what runs [main], and dune's files *)
let write_project ?(read_source=read_file) ?(private_extract=false)
    ?(capture_generated=(fun _ _ -> ())) ~state ~modules ~libraries ~js ~directives dir =
  mkdir_p dir;
  let assembly_contracts=SomaOcamlBindings.native_assembly_contracts()in
  let expected = Hashtbl.create 17 in
  let file f contents =
    Hashtbl.replace expected f (SomaMerkle.string contents);
    capture_generated f contents;
    ignore (update_file (Filename.concat dir f) contents) in
  if private_extract then begin
    (* A persistent cached prog.ml is never evidence of what this invocation
       extracted. Generate into a new private directory, then bind the copied
       bytes to the same producer hashes as the wrappers and own modules. *)
    let staging = CUnix.mktemp_dir ~temp_dir:dir ".soma-extraction-" "" in
    Fun.protect ~finally:(fun () ->
        Array.iter (fun f -> try Sys.remove (Filename.concat staging f) with Sys_error _ -> ())
          (Sys.readdir staging);
        try Unix.rmdir staging with Unix.Unix_error _ -> ()) (fun () ->
        extract ~state ~modules staging;
        List.iter (fun f -> file f (read_file (Filename.concat staging f))) ["prog.ml"; "prog.mli"])
  end else extract ~state ~modules dir;
  file "soma_main.ml" (entry_ml ());
  if SomaNative.loaded () then begin
    file "soma_effect.ml" SomaNative.ml;
    file "soma_handles.ml" (SomaMirage.handles_ml ~lwt:true)
  end;
  file "float64.ml" SomaMirage.float64_ml;
  file "uint63.ml" SomaMirage.uint63_ml;
  file "soma_word64.ml" SomaMirage.word64_ml;
  (* Soma.Host's primitives are Soma's own module *)
  let host = List.exists (fun (m : SomaForeign.ocaml_module) -> m.ml_file = None && m.top = host_module) modules in
  if host then begin
    file "soma_host.ml" SomaHost.ml;
    file "soma_host_io.c" SomaHost.io_c
  end;
  let own = SomaOcamlBindings.write_files ~file ~read_file:read_source ~directives modules in
  let assemblies=SomaOcamlBindings.write_assemblies ~file ~read_source ~contracts:assembly_contracts ~modules
    ~program:(read_file(Filename.concat dir "prog.ml"))
    ~interface:(read_file(Filename.concat dir "prog.mli"))
    ~bindings:(read_file(Filename.concat dir(SomaOcamlBindings.bindings_filename())))in
  let made = List.sort_uniq String.compare
      (["prog.ml"; "prog.mli"; "soma_main.ml"; "float64.ml"; "uint63.ml"; "soma_word64.ml"; "soma_nat.ml"; SomaOcamlBindings.bindings_filename(); "native_abi.manifest"; "native_owned.manifest"; "native_variants.manifest"; "native_callables.manifest"]
       @ (if host then ["soma_host.ml"; "soma_host_io.c"] else [])
       @ (if SomaNative.loaded () then ["soma_effect.ml"; "soma_handles.ml"] else []) @ own @ assemblies) in
  let names = List.sort_uniq String.compare (List.map (fun f ->
      String.capitalize_ascii (Filename.remove_extension f)) (List.filter (fun f -> Filename.check_suffix f ".ml") made)) in
  let c = SomaOcamlBindings.c_stub_names own in
  if js && c <> [] then
    CErrors.user_err Pp.(str "a page cannot call C: " ++ str (String.concat ", " c) ++
                         str " are C modules, which only an executable or an image runs.");
  file "dune" (dune_file ~js ~host ~c ~modules:names libraries);
  record_generated_files ~capture_generated dir made expected

