(* "...", as opam writes it: UTF-8 as it is *)
let opam_string s =
  let b = Buffer.create (String.length s + 2) in
  Buffer.add_char b '"';
  String.iter (function
      | '"' | '\\' as c -> Buffer.add_char b '\\'; Buffer.add_char b c
      | '\n' -> Buffer.add_string b "\\n"
      | c -> Buffer.add_char b c) s;
  Buffer.add_char b '"';
  Buffer.contents b

(* with soma.toml, the project's name, version and description, and the
   versions of packages its [opam] has *)
let opam_file ~source ~project ~packages =
  let versions = match project with Some p -> p.SomaProject.opam | None -> [] in
  let packages = packages @ List.filter (fun p -> not (List.mem p packages)) (List.map fst versions) in
  let depend p = match List.assoc_opt p versions with
    | Some v -> Printf.sprintf "  %S {= %S}\n" p v
    | None -> Printf.sprintf "  %S\n" p in
  let synopsis = match project with
    | Some { SomaProject.description = Some d; _ } -> d
    | _ -> Filename.basename source ^ ", extracted to OCaml by Soma" in
  Printf.sprintf "%s\nopam-version: \"2.0\"\n%ssynopsis: %s\n\
                  depends: [\n  \"ocaml\"\n  \"dune\" {>= \"3.0\"}\n%s]\n\
                  build: [[\"dune\" \"build\" \"--profile\" \"release\"]]\n"
    (String.map (fun c -> if c = ';' then '#' else c) extract_marker)
    (match project with
     | Some p -> Printf.sprintf "version: %S\n" (SomaProject.version_to_string p.SomaProject.version)
     | None -> "")
    (opam_string synopsis)
    (String.concat "" (List.map depend packages))

(* [soma extract FILE -o DIR]: the program's OCaml project, in [dir], to be
   built by dune, with or without Soma *)
let export ~state ~source dir =
  ignore (main_reference ());
  if SomaMirage.requires_mirage () then
    error Pp.(str "a program that requires Sandbox is a MirageOS unikernel, which soma extract does not" ++ spc () ++
              str "write as an OCaml project yet: soma build builds its image.");
  let modules, libraries = checked_modules () in
  if Sys.file_exists dir && Sys.readdir dir <> [||] then begin
    let project = Filename.concat dir "dune-project" in
    (* its second line, the first being dune's (lang ...) *)
    let ours = Sys.file_exists project &&
               List.exists (String.starts_with ~prefix:extract_marker) (read_lines project) in
    if not ours then
      error Pp.(str dir ++ str " is not empty, and soma extract did not make it:" ++ spc () ++
                str "extract into a new directory (-o DIR).")
  end;
  let switch, managed = opam_switch () in
  let switch = if managed && not (Sys.file_exists (Filename.concat switch "_opam")) then None else Some switch in
  let js = for_browser ?switch libraries in
  write_project ~state ~modules ~libraries ~js ~directives:false dir;
  (try Sys.remove (Filename.concat dir "extract.soma") with Sys_error _ -> ());
  let name = Filename.remove_extension (Filename.basename source) in
  let project = SomaProject.of_file source in
  let package = match project with
    | Some p -> p.SomaProject.name
    | None -> package_name name in
  let packages = List.sort_uniq compare (List.map package_of libraries) in
  let file f contents = ignore (update_file (Filename.concat dir f) contents) in
  file "dune-project" ("(lang dune 3.0)\n" ^ extract_marker ^ " " ^ Filename.basename source ^ "\n");
  file (package ^ ".opam") (opam_file ~source ~project ~packages);
  file "README.md" (extracted_readme ~source ~package ~packages ~js);
  if js then file "index.html"
      (page_html ~script:"_build/default/soma_main.bc.js" name);
  Feedback.msg_notice Pp.(str "OCaml: extracted " ++ str (Filename.basename source) ++ str " into " ++ str dir ++
                          str "; build it with: cd " ++ str dir ++
                          str " && opam install . --deps-only && dune build --profile release")

let build ~state ~source ~vo_file =
  match Sys.getenv_opt "SOMA_OCAML_EXTRACT" with
  | Some dir when dir <> "" -> export ~state ~source dir
  | _ ->
  if getenv_default "SOMA_OCAML_BUILD" "1" <> "0" && getenv_default "SOMA_MIRAGE_BUILD" "1" <> "0" then
  match used_modules () with
  | [] -> ()
  | _ ->
    let modules, libraries = checked_modules () in
    let switch, managed = opam_switch () in
    let versions = match SomaProject.of_file source with
      | Some p -> p.SomaProject.opam
      | None -> [] in
    ensure_packages ~switch ~managed ~versions libraries;
    let js = for_browser ~switch libraries in
    (* one project for each program, kept between builds *)
    let source = CUnix.canonical_path_name source in
    let name = Filename.remove_extension (Filename.basename source) in
    let dir = List.fold_left Filename.concat (cache_dir ())
        ["build"; name ^ "-" ^ String.sub (Digest.to_hex (Digest.string source)) 0 8] in
    write_project ~state ~modules ~libraries ~js ~directives:true dir;
    ignore (update_file (Filename.concat dir "dune-project") "(lang dune 3.0)\n");
    let target = if js then "./soma_main.bc.js" else "./soma_main.exe" in
    let log = Filename.concat dir "build.log" in
    let script = Printf.sprintf "cd %s && dune build --profile release --root . %s"
        (Filename.quote dir) target in
    if not (run ~log ["opam"; "exec"; "--switch=" ^ switch; "--"; "sh"; "-c"; script]) then
      error Pp.(str "building " ++ str (Filename.basename source) ++ str " with " ++
                str (String.concat ", " (List.map (fun (m : SomaForeign.ocaml_module) ->
                    match m.ml_file with Some f -> Filename.basename f | None -> m.top) modules)) ++
                str " failed; the end of " ++ str log ++ str ":" ++ fnl () ++ str (tail_of_file log) ++ fnl () ++
                str "(" ++ str dir ++ str "/soma_bindings.ml has each value that a .definition declares," ++
                spc () ++ str "at its declared type)");
    let built = List.fold_left Filename.concat dir ["_build"; "default"; Filename.basename target] in
    let out = Filename.remove_extension vo_file in
    if js then begin
      SomaMirage.write_file (out ^ ".js") (read_file built);
      SomaMirage.write_file (out ^ ".html") (page_html (Filename.basename out));
      Feedback.msg_notice Pp.(str "OCaml: built " ++ str (out ^ ".html") ++ str ", with " ++
                              str (Filename.basename out ^ ".js") ++ str "; open it in a browser")
    end else begin
      SomaMirage.copy_file ~src:built ~dst:(out ^ ".exe");
      Feedback.msg_notice Pp.(str "OCaml: built " ++ str (out ^ ".exe") ++ str "; run it with: " ++
                              str (out ^ ".exe"))
    end
