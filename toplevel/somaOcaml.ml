(* * The modules main uses *)

let main_reference () =
  try Nametab.locate (Libnames.qualid_of_ident (Id.of_string "main"))
  with Not_found -> error Pp.(str "the program defines no main, which is what OCaml runs.")

(* The constants [main] depends on, without a body: those of OCaml modules
   among them *)
let used_modules () =
  let modules = !SomaForeign.ocaml_modules () in
  if modules = [] then [] else
  match (try Some (Nametab.locate (Libnames.qualid_of_ident (Id.of_string "main"))) with Not_found -> None) with
  | None -> []
  | Some main ->
    let st = Conv_oracle.get_transp_state (Environ.oracle (Global.env ())) in
    let _, assums = Assumptions.assumptions (Library.indirect_accessor [@ocaml.alert "-deprecated"]) st [main] in
    let used = Printer.ContextObjectMap.fold (fun o _ acc -> match o with
        | Printer.Axiom (Printer.Constant k, _) -> Cset_env.add k acc
        | _ -> acc) assums Cset_env.empty in
    List.filter (fun (m : SomaForeign.ocaml_module) ->
        List.exists (fun (c, _, _) -> Cset_env.mem c used) m.items) modules

let header = "(* Generated by Soma (toplevel/somaOcaml.ml). *)\n"

(* the type variables of an OCaml type, in order: ['s; 'a] *)
let type_variables ty =
  let n = String.length ty in
  let rec go i acc =
    if i >= n then List.rev acc
    else if ty.[i] = '\'' then
      let j = ref (i + 1) in
      while !j < n && (match ty.[!j] with 'a'..'z' | 'A'..'Z' | '0'..'9' | '_' -> true | _ -> false) do incr j done;
      let v = String.sub ty i (!j - i) in
      go !j (if List.mem v acc then acc else v :: acc)
    else go (i + 1) acc in
  go 0 []

(* A declaration's name in soma_bindings.ml: Async.Deferred.bind is
   async__Deferred__bind *)
let binding_name (m : SomaForeign.ocaml_module) path =
  String.uncapitalize_ascii m.top ^ "__" ^ String.concat "__" (String.split_on_char '.' path)

(* soma_bindings.ml: each value that the definitions declare, at its
   declared type, its type variables those of a polymorphic value, so that
   OCaml checks it. Each is applied to as many arguments as it is declared
   with: so a library's labels need not be declared (Deferred.bind's ~f,
   given in its place), and its optional arguments are left out, as OCaml
   allows of an application of all its arguments. *)
let bindings_ml modules =
  header ^ "(* Each value that a .definition declares, at its declared type. *)\n" ^
  String.concat "" (List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      let definition = match m.ml_file with
        | Some f -> Filename.remove_extension (Filename.basename f) ^ ".definition"
        | None -> String.uncapitalize_ascii m.top ^ ".definition" in
      List.filter_map (fun (_, path, item) -> match item with
          | SomaForeign.OCamlType _ -> None
          | SomaForeign.OCamlValue (ty, labels) ->
            let vars = type_variables ty in
            let poly = if vars = [] then "" else String.concat " " vars ^ ". " in
            let args = List.mapi (fun i _ -> Printf.sprintf "a%d" i) labels in
            (* a named argument is given by its label: ~attrs:a1 *)
            let given = List.map2 (fun a l -> match l with
                | Some l -> Printf.sprintf "~%s:%s" l a
                | None -> a) args labels in
            let value = m.top ^ "." ^ path in
            let body = if args = [] then value
              else Printf.sprintf "fun %s -> %s %s" (String.concat " " args) value (String.concat " " given) in
            Some (Printf.sprintf "\n(* %s: %s *)\nlet %s : %s%s =\n  %s\n"
                    definition path (binding_name m path) poly ty body))
        m.items) modules)

(* soma_nat.ml: nat as extraction makes it in prog.ml, which a module of
   the project cannot name (prog.ml uses it): a declared type's nat is
   this one, of the same constructors, so of the same values *)
let soma_nat_ml =
  header ^ "(* Soma's nat, as extracted: 0 is O, and n + 1 is S n. *)\n\
            type nat = O | S of nat\n"

let mentions_nat ty = CString.string_contains ~where:ty ~what:"Soma_nat.nat"

(* * The switch *)

(* lwt.unix is a library of the opam package lwt *)
let package_of library = match String.index_opt library '.' with
  | Some i -> String.sub library 0 i
  | None -> library

(* What the switch has, as lines "package version" (or "package", in a
   record of an earlier Soma): opam's own list, asked of opam *)
let installed_in switch =
  let out = Filename.temp_file "soma-ocaml" ".installed" in
  let listed = run ~log:out ["opam"; "list"; "--switch=" ^ switch; "--installed"; "--short";
                             "--columns=name,version"; "--color=never"] in
  let said = tail_of_file ~lines:5 out in
  let lines = read_lines out in
  (try Sys.remove out with Sys_error _ -> ());
  (* a switch opam can't list is not an empty one: installing into it would
     fail too, for a reason further from the cause *)
  if not listed then
    error Pp.(str "asking opam what the switch " ++ str switch ++ str " has failed:" ++ fnl () ++
              str said ++ fnl () ++
              str "opam writes its lock files and its log (in $OPAMROOT/log) even to list a switch." ++ spc () ++
              str "If another user owns the switch, let this user write those, or build as that user.");
  List.filter_map (fun l -> match List.filter (( <> ) "") (String.split_on_char ' ' l) with
      | [p; v] -> Some (p ^ " " ^ v)
      | _ -> None) lines

(* whether the switch has [package], at [version] if there is one *)
let has lines (package, version) =
  List.exists (fun l -> match String.split_on_char ' ' l, version with
      | p :: _, None -> p = package
      | [p; v], Some w -> p = package && v = w
      | _ -> false) lines

(* The opam packages that [libraries] need, installed in the switch, each
   at its version in [versions] (soma.toml's [opam]), or else any: once.
   What the switch has is recorded in the cache, in [installed]; when the
   record does not have them, opam is asked, and only what opam does not
   have is installed. So a switch made elsewhere (a CI image, with
   $SOMA_OCAML_SWITCH and a cache of its own) is used as it is, offline. *)
let ensure_packages ~switch ~managed ?(versions = []) libraries =
  let dir = cache_dir () in
  mkdir_p dir;
  let installed = Filename.concat dir
      (if managed then "installed" else "installed-" ^ Digest.to_hex (Digest.string switch)) in
  let names = (if managed then ["ocaml-base-compiler"] else []) @ ["dune"] @
              List.sort_uniq compare (List.map package_of libraries) in
  let names = names @ List.filter (fun p -> not (List.mem p names)) (List.map fst versions) in
  let wanted = List.map (fun p -> p, List.assoc_opt p versions) names in
  let record lines =
    (* the cache may be read-only: the record only saves asking opam *)
    try SomaMirage.write_file installed (String.concat "\n" lines ^ "\n")
    with Sys_error _ | Unix.Unix_error _ -> () in
  if not (List.for_all (has (read_lines installed)) wanted) then begin
    let log = Filename.concat dir "setup.log" in
    let fail what =
      error Pp.(str what ++ str " failed; the end of " ++ str log ++ str ":" ++ fnl () ++
                str (tail_of_file log) ++ fnl () ++
                str "A package that needs a library of the system says so above: install it," ++ spc () ++
                str "or point pkg-config at it (PKG_CONFIG_PATH), and build again.") in
    ignore (SomaOpam.ensure_switch ~who:"OCaml" ~log);
    let have = installed_in switch in
    let missing = List.filter (fun w -> not (has have w)) wanted in
    if missing = [] then record have else begin
      let atom (p, v) = match v with Some v -> p ^ "." ^ v | None -> p in
      (* said as it happens, on stderr, which soma does not wait for *)
      Printf.eprintf "OCaml: installing %s into the opam switch %s (once; this takes a while; %s)\n%!"
        (String.concat ", " (List.map atom missing)) switch log;
      (* the system's libraries are looked for by the packages that need
         them, rather than by opam's list of the system's packages *)
      if not (run ~log (["opam"; "install"; "--switch=" ^ switch; "-y"; "--assume-depexts"] @
                        List.map atom missing)) then
        fail "installing the packages";
      record (installed_in switch)
    end
  end

(* Whether [libraries] are made for the browser: their packages depend on
   js_of_ocaml. Recorded in [targets], once for each set. *)
let for_browser ?switch libraries =
  let packages = List.sort_uniq compare (List.map package_of libraries) in
  if packages = [] || not (command_exists "opam") then List.mem "js_of_ocaml" packages else
  let switch_args = match switch with Some s -> ["--switch=" ^ s] | None -> [] in
  let switch = Option.default "" switch in
  let key = Digest.to_hex (Digest.string (switch ^ " " ^ String.concat "," packages)) in
  let targets = Filename.concat (cache_dir ()) "targets" in
  let known = read_lines targets in
  match List.find_map (fun l -> match String.split_on_char ' ' l with
      | [k; t] when k = key -> Some (t = "js")
      | _ -> None) known with
  | Some js -> js
  | None ->
    let out = Filename.temp_file "soma-ocaml" ".deps" in
    (* their dependencies as installed, or else as opam's repository has
       them *)
    let list installed =
      if run ~log:out (["opam"; "list"] @ switch_args @ installed @
                       ["--recursive"; "--short"; "--required-by=" ^ String.concat "," packages])
      then Some (read_lines out) else None in
    let deps = match list ["--installed"] with
      | Some (_ :: _ as deps) -> Some deps
      | _ -> list [] in
    let ok = Option.has_some deps in
    let deps = Option.default [] deps in
    (try Sys.remove out with Sys_error _ -> ());
    let js = List.mem "js_of_ocaml" deps || List.mem "js_of_ocaml" packages in
    if ok then SomaMirage.write_file targets
        (String.concat "\n" (known @ [key ^ " " ^ (if js then "js" else "exe")]) ^ "\n");
    js

(* * The program *)

(* A program that extracts [nat] as OCaml's [int] (it requires
   ExtrOcamlNatInt) gets what an image gets with it: Nat's comparisons and
   division, and String's length, get and substring, as OCaml's
   (SomaMirage.nat_string_extraction). Otherwise they count in [nat] a
   character at a time, which copies the rest of a native string at each
   one: Soma.Wire's take_frame of a 200 KB frame took 80 s instead of a
   millisecond. *)
let nat_int_library = DirPath.make (List.rev_map Id.of_string ["Stdlib"; "extraction"; "ExtrOcamlNatInt"])
let extracts_nat_as_int () = List.exists (DirPath.equal nat_int_library) (Library.loaded_libraries ())

(* Extracts [main] into [dir]/prog.ml, each declaration of the modules
   being what they have of its name *)
let extract ~state ~modules dir =
  let cmds = Filename.concat dir "extract.soma" in
  let lines = List.concat_map (fun (m : SomaForeign.ocaml_module) ->
      List.map (fun (c, path, item) ->
          let soma = Libnames.string_of_path (Nametab.path_of_global (GlobRef.ConstRef c)) in
          match item with
          | SomaForeign.OCamlValue (ty, labels) when mentions_nat ty ->
            (* Soma_nat.nat is prog.ml's nat by its values, not its name:
               soma_bindings.ml checks the value at Soma_nat.nat, and
               here it is taken at prog.ml's nat, without converting.
               A function is applied, so that it stays polymorphic. *)
            let args = String.concat "" (List.mapi (fun i _ -> Printf.sprintf " a%d" i) labels) in
            let value = Printf.sprintf "Obj.magic Soma_bindings.%s%s" (binding_name m path) args in
            Printf.sprintf "Extract Constant %s => \"(%s)\".\n" soma
              (if args = "" then value else "fun" ^ args ^ " -> " ^ value)
          | SomaForeign.OCamlValue _ ->
            Printf.sprintf "Extract Constant %s => \"Soma_bindings.%s\".\n" soma (binding_name m path)
          | SomaForeign.OCamlType n ->
            let ps = List.init n (fun i -> "'" ^ String.make 1 (Char.chr (Char.code 'a' + i))) in
            let applied = match ps with
              | [] -> "" | [p] -> p ^ " " | ps -> "(" ^ String.concat ", " ps ^ ") " in
            Printf.sprintf "Extract Constant %s %s => \"%s%s.%s\".\n" soma
              (String.concat " " (List.map (Printf.sprintf "%S") ps)) applied m.top path)
        m.items) modules in
  SomaMirage.write_file cmds (Printf.sprintf
    "From Corelib Require Extraction PrimFloat FloatClass PrimInt63 CarryType.\n\
     Set Extraction Output Directory %S.\n\
     From Stdlib Require ExtrOcamlBasic ExtrOcamlNativeString.\n\
     %s%s%s\
     Definition soma_main (_ : unit) := main.\n\
     Extraction Inline main.\n\
     Extraction \"prog\" soma_main.\n" dir SomaMirage.float_extraction
       (if extracts_nat_as_int () then SomaMirage.nat_string_extraction else "") (String.concat "" lines));
  Dumpglob.push_output Dumpglob.NoGlob;
  (* its Extraction "prog" goes to [dir], the output directory it sets *)
  SomaImport.generated_output := true;
  Fun.protect ~finally:(fun () -> SomaImport.generated_output := false; Dumpglob.pop_output ()) (fun () ->
      ignore (Vernac.load_vernac ~check:true ~state cmds))

(* whether [main] is a string, which the program prints *)
let main_is_string () =
  let env = Global.env () in
  let ty, _ = Typeops.type_of_global_in_context env (main_reference ()) in
  Rocqlib.has_ref "core.string.type" &&
  EConstr.isRefX env (Evd.from_env env) (Rocqlib.lib_ref "core.string.type")
    (Reductionops.whd_all env (Evd.from_env env) (EConstr.of_constr ty))

(* what runs [main], and prints it if it is a string: a run-time error, a
   cast that fails, says so *)
let entry_ml () = header ^ Printf.sprintf {soma|let () =
  try %s (Prog.soma_main ())
  with e ->|soma} (if main_is_string () then "print_endline" else "ignore") ^ {soma|
    prerr_endline ("Run-time error: " ^ Printexc.to_string e);
    exit 1
|soma}

