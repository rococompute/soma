(* Soma: a program whose [main] uses OCaml modules (FILE.ml, declared by
   FILE.definition, or a library's module, declared by a .definition next
   to no module: plugins/soma_ocaml) is built with them by OCaml. After
   [rocq c prog.soma] has checked it, [main] is extracted to OCaml, next to
   the project's modules and soma_bindings.ml, which has each declared
   value at its declared type, so that OCaml checks the declarations, and
   dune builds them with the libraries that the definitions name
   ([OCaml Library "bonsai.web".]).

   A program that uses a library made for the browser (one that depends on
   js_of_ocaml) is built into [prog.js], with [prog.html], the page that
   runs it in [<div id="app">]; the others into the executable [prog.exe].
   Building the program evaluates [main], once, as OCaml does a module's
   value: what it does is what its OCaml functions do.

   The libraries come from opam, in the switch [$SOMA_OCAML_SWITCH], or
   else one that Soma makes and keeps in [$XDG_CACHE_HOME/soma/ocaml] (or
   [~/.cache/soma/ocaml]), where it installs what the programs need, once
   each. The projects are kept there too, in [build/], one per program.
   Setting [SOMA_OCAML_BUILD=0] skips the build. *)

