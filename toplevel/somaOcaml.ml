let dune_file ~js libraries =
  let ppx, libs = List.partition (fun l -> String.starts_with ~prefix:"ppx_" l) libraries in
  Printf.sprintf
    ";; Generated by Soma (toplevel/somaOcaml.ml).\n\
     (executable\n (name soma_main)\n (modes %s)\n (libraries %s)\n%s\
    \ (flags (:standard -w -a)))\n"
    (if js then "js" else "exe") (String.concat " " libs)
    (if ppx = [] then "" else Printf.sprintf " (preprocess (pps %s))\n" (String.concat " " ppx))

(* the modules main uses, checked, and the libraries they use *)
let checked_modules () =
  let modules = used_modules () in
  ignore (main_reference ());
  if SomaMirage.requires_mirage () then
    error Pp.(str "a program that requires Sandbox is a unikernel, which cannot use OCaml modules yet.");
  (* two modules of the project of one name would be one module *)
  let names = List.filter_map (fun (m : SomaForeign.ocaml_module) ->
      Option.map (fun _ -> m.top) m.ml_file) modules in
  List.iter (fun n ->
      if List.length (List.filter (String.equal n) names) > 1 then
        error Pp.(str "the program uses two OCaml modules named " ++ str n ++ str ".");
      if List.mem n ["Prog"; "Soma_main"; "Soma_bindings"; "Soma_nat"; "Float64"; "Uint63"] then
        error Pp.(str "an OCaml module cannot be named " ++ str n ++ str ", the name of one Soma makes."))
    names;
  modules, List.sort_uniq compare (List.concat_map (fun (m : SomaForeign.ocaml_module) -> m.libraries) modules)

(* The OCaml project of the program, in [dir]: [main] extracted, the
   bindings, the project's modules (with line directives to them when
   [~directives], so that OCaml's errors are about the files themselves),
   what runs [main], and dune's files *)
let write_project ~state ~modules ~libraries ~js ~directives dir =
  mkdir_p dir;
  extract ~state ~modules dir;
  let file f contents = ignore (update_file (Filename.concat dir f) contents) in
  file "dune" (dune_file ~js libraries);
  file "soma_main.ml" (entry_ml ());
  file "float64.ml" SomaMirage.float64_ml;
  file "uint63.ml" SomaMirage.uint63_ml;
  file "soma_nat.ml" soma_nat_ml;
  file "soma_bindings.ml" (bindings_ml modules);
  List.iter (fun (m : SomaForeign.ocaml_module) ->
      Option.iter (fun ml ->
          file (String.uncapitalize_ascii m.top ^ ".ml")
            ((if directives then Printf.sprintf "# 1 %S\n" ml else "") ^ read_file ml))
        m.ml_file)
    modules

