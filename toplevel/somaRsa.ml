#define KEY(v) (*(EVP_PKEY **)Data_custom_val(v))
static void key_finalize(value v) { EVP_PKEY_free(KEY(v)); KEY(v) = NULL; }
static struct custom_operations key_ops = {
  "soma.openssl.rsa.v1", key_finalize, custom_compare_default,
  custom_hash_default, custom_serialize_default, custom_deserialize_default,
  custom_compare_ext_default, custom_fixed_length_default
};
static void rejected(void) {
  ERR_clear_error(); /* Never propagate provider errors or key values. */
  caml_failwith("RSA provider operation failed");
}
static const char *names[] = {
  OSSL_PKEY_PARAM_RSA_N, OSSL_PKEY_PARAM_RSA_E, OSSL_PKEY_PARAM_RSA_D,
  OSSL_PKEY_PARAM_RSA_FACTOR1, OSSL_PKEY_PARAM_RSA_FACTOR2,
  OSSL_PKEY_PARAM_RSA_EXPONENT1, OSSL_PKEY_PARAM_RSA_EXPONENT2,
  OSSL_PKEY_PARAM_RSA_COEFFICIENT1
};
CAMLprim value soma_rsa_generate(value bits) {
  CAMLparam1(bits); CAMLlocal1(key);
  key = caml_alloc_custom_mem(&key_ops, sizeof(EVP_PKEY *), 32768);
  KEY(key) = NULL;
  int n = Int_val(bits);
  if (n < 2048 || n > 8192 || n % 256 != 0) rejected();
  EVP_PKEY_CTX *ctx = EVP_PKEY_CTX_new_from_name(NULL, "RSA", "provider=default");
  int ok = ctx && EVP_PKEY_keygen_init(ctx) > 0 &&
    EVP_PKEY_CTX_set_rsa_keygen_bits(ctx, n) > 0 &&
    EVP_PKEY_generate(ctx, &KEY(key)) > 0;
  EVP_PKEY_CTX_free(ctx);
  if (!ok) rejected();
  CAMLreturn(key);
}
CAMLprim value soma_rsa_import(value parts) {
  CAMLparam1(parts); CAMLlocal1(key);
  key = caml_alloc_custom_mem(&key_ops, sizeof(EVP_PKEY *), 32768);
  KEY(key) = NULL;
  mlsize_t count = Wosize_val(parts);
  if (count != 2 && count != 8) rejected();
  BIGNUM *bn[8] = {0};
  OSSL_PARAM_BLD *bld = OSSL_PARAM_BLD_new();
  OSSL_PARAM *params = NULL;
  EVP_PKEY_CTX *ctx = NULL, *check = NULL;
  int ok = bld != NULL;
  for (mlsize_t i = 0; ok && i < count; ++i) {
    value s = Field(parts, i);
    mlsize_t len = caml_string_length(s);
    if (!len || len > 2048 || len % 2) { ok = 0; break; }
    for (mlsize_t j = 0; j < len; ++j) {
      char c = String_val(s)[j];
      if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') ||
            (c >= 'A' && c <= 'F'))) { ok = 0; break; }
    }
    if (ok) ok = BN_hex2bn(&bn[i], String_val(s)) == (int)len &&
                 OSSL_PARAM_BLD_push_BN(bld, names[i], bn[i]);
  }
  if (ok) {
    params = OSSL_PARAM_BLD_to_param(bld);
    ctx = EVP_PKEY_CTX_new_from_name(NULL, "RSA", "provider=default");
    ok = params && ctx && EVP_PKEY_fromdata_init(ctx) > 0 &&
      EVP_PKEY_fromdata(ctx, &KEY(key), count == 8 ? EVP_PKEY_KEYPAIR : EVP_PKEY_PUBLIC_KEY, params) > 0;
  }
  if (ok) {
    int bits = EVP_PKEY_get_bits(KEY(key));
    check = EVP_PKEY_CTX_new_from_pkey(NULL, KEY(key), "provider=default");
    /* SP800-56B public_check imposes 2^16 < e < 2^256 and would reject
       existing valid keys. Use bounded structural checks for public keys;
       the default-provider pairwise check below fully validates private keys. */
    ok = bits >= 2047 && bits <= 8192 && check && BN_is_odd(bn[0]) &&
      BN_is_odd(bn[1]) && !BN_is_one(bn[1]) && !BN_is_zero(bn[1]) &&
      BN_num_bits(bn[1]) <= 8192;
    /* Includes primality, n=p*q, e*d relation and supplied CRT components.
       The default provider accepts mathematically valid composite exponents. */
    if (ok && count == 8) ok = EVP_PKEY_private_check(check) == 1 &&
                              EVP_PKEY_pairwise_check(check) == 1;
  }
  EVP_PKEY_CTX_free(check); EVP_PKEY_CTX_free(ctx);
  if (params) {
    for (OSSL_PARAM *p = params; p->key; ++p)
      if (p->data) OPENSSL_cleanse(p->data, p->data_size);
  }
  OSSL_PARAM_free(params); OSSL_PARAM_BLD_free(bld);
  for (int i = 0; i < 8; ++i) BN_clear_free(bn[i]);
  if (!ok) { EVP_PKEY_free(KEY(key)); KEY(key) = NULL; rejected(); }
  CAMLreturn(key);
}
CAMLprim value soma_rsa_component(value key, value index, value width) {
  CAMLparam3(key, index, width); CAMLlocal1(out);
  int i = Int_val(index), n = Int_val(width);
  if (!KEY(key) || i < 0 || i >= 8 || n <= 0 || n > 1024) rejected();
  out = caml_alloc_string(2 * n);
  unsigned char bytes[1024];
  BIGNUM *bn = NULL;
  int ok = EVP_PKEY_get_bn_param(KEY(key), names[i], &bn) &&
           BN_bn2binpad(bn, bytes, n) == n;
  BN_clear_free(bn);
  if (!ok) { OPENSSL_cleanse(bytes, sizeof bytes); rejected(); }
  const char *hex = "0123456789abcdef";
  for (int j = 0; j < n; ++j) {
    Bytes_val(out)[2*j] = hex[bytes[j] >> 4];
    Bytes_val(out)[2*j+1] = hex[bytes[j] & 15];
  }
  OPENSSL_cleanse(bytes, sizeof bytes);
  CAMLreturn(out);
}
/* Compatibility verification for legacy exponents outside EVP's supported
   range. Only PUBLIC operands use BN_mod_exp. PKCS#1 type-1 padding is checked
   by OpenSSL; DigestInfo is required to be the exact SHA-256 DER encoding.
   This is intentionally explicit, not a fallback to Soma's reference RSA. */
static int verify_legacy(EVP_PKEY *key, const char *msg, size_t len,
                         const unsigned char *sig, size_t siglen) {
  static const unsigned char prefix[19] = {
    0x30,0x31,0x30,0x0d,0x06,0x09,0x60,0x86,0x48,0x01,
    0x65,0x03,0x04,0x02,0x01,0x05,0x00,0x04,0x20
  };
  BIGNUM *n = NULL, *e = NULL, *s = NULL, *m = NULL;
  BN_CTX *ctx = BN_CTX_new();
  unsigned char encoded[1024], recovered[1024], expected[51];
  unsigned int digest_len = 0;
  int width = EVP_PKEY_get_size(key);
  int ok = width > 0 && width <= 1024 && siglen == (size_t)width && ctx &&
    EVP_PKEY_get_bn_param(key, OSSL_PKEY_PARAM_RSA_N, &n) &&
    EVP_PKEY_get_bn_param(key, OSSL_PKEY_PARAM_RSA_E, &e);
  if (ok) {
    s = BN_bin2bn(sig, (int)siglen, NULL); m = BN_new();
    ok = s && m && BN_cmp(s, n) < 0 && BN_mod_exp(m, s, e, n, ctx) &&
      BN_bn2binpad(m, encoded, width) == width;
  }
  if (ok) {
    /* No permissive ASN.1 parser, alternate hashes, trailing data or short PS. */
    int got = RSA_padding_check_PKCS1_type_1(recovered, sizeof recovered,
                                            encoded, width, width);
    memcpy(expected, prefix, sizeof prefix);
    ok = got == (int)sizeof expected &&
      EVP_Digest(msg, len, expected + sizeof prefix, &digest_len, EVP_sha256(), NULL) &&
      digest_len == 32 && CRYPTO_memcmp(recovered, expected, sizeof expected) == 0;
  }
  BN_free(n); BN_free(e); BN_free(s); BN_free(m); BN_CTX_free(ctx);
  ERR_clear_error();
  return ok;
}
static int verify(EVP_PKEY *key, const char *msg, size_t len,
                  const unsigned char *sig, size_t siglen) {
  BIGNUM *e = NULL, *n = NULL;
  int got = EVP_PKEY_get_bn_param(key, OSSL_PKEY_PARAM_RSA_E, &e) &&
            EVP_PKEY_get_bn_param(key, OSSL_PKEY_PARAM_RSA_N, &n);
  int legacy = got && (BN_cmp(e, n) >= 0 ||
    (BN_num_bits(n) > OPENSSL_RSA_SMALL_MODULUS_BITS &&
     BN_num_bits(e) > OPENSSL_RSA_MAX_PUBEXP_BITS));
  BN_free(e); BN_free(n);
  if (!got) return 0;
  if (legacy) return verify_legacy(key, msg, len, sig, siglen);
  EVP_MD_CTX *ctx = EVP_MD_CTX_new();
  EVP_PKEY_CTX *pkctx = NULL;
  int ok = ctx && EVP_DigestVerifyInit_ex(ctx, &pkctx, "SHA256", NULL,
      "provider=default", key, NULL) > 0 &&
    EVP_PKEY_CTX_set_rsa_padding(pkctx, RSA_PKCS1_PADDING) > 0 &&
    EVP_DigestVerify(ctx, sig, siglen, (const unsigned char *)msg, len) == 1;
  EVP_MD_CTX_free(ctx);
  ERR_clear_error();
  return ok;
}
CAMLprim value soma_rsa_sign(value key, value msg) {
  CAMLparam2(key, msg); CAMLlocal1(out);
  if (!KEY(key)) rejected();
  EVP_MD_CTX *ctx = EVP_MD_CTX_new();
  EVP_PKEY_CTX *pkctx = NULL;
  unsigned char signature[1024];
  size_t len = sizeof signature;
  /* OpenSSL's default RSA private operation keeps its blinding and CRT
     hardening enabled. Never use RSA_NO_PADDING or disable blinding. */
  int ok = ctx && EVP_DigestSignInit_ex(ctx, &pkctx, "SHA256", NULL,
      "provider=default", KEY(key), NULL) > 0 &&
    EVP_PKEY_CTX_set_rsa_padding(pkctx, RSA_PKCS1_PADDING) > 0 &&
    EVP_DigestSign(ctx, signature, &len,
      (const unsigned char *)String_val(msg), caml_string_length(msg)) > 0;
  EVP_MD_CTX_free(ctx);
  if (ok) ok = len == (size_t)EVP_PKEY_get_size(KEY(key)) &&
    verify(KEY(key), String_val(msg), caml_string_length(msg), signature, len);
  if (!ok) { OPENSSL_cleanse(signature, sizeof signature); rejected(); }
  out = caml_alloc_initialized_string(len, (const char *)signature);
  OPENSSL_cleanse(signature, sizeof signature);
  CAMLreturn(out);
}
CAMLprim value soma_rsa_verify(value key, value msg, value signature) {
  CAMLparam3(key, msg, signature);
  int ok = KEY(key) && caml_string_length(signature) == (mlsize_t)EVP_PKEY_get_size(KEY(key)) &&
    verify(KEY(key), String_val(msg), caml_string_length(msg),
      (const unsigned char *)String_val(signature), caml_string_length(signature));
  CAMLreturn(Val_bool(ok));
}
