(* Lightlang: a program that requires [Lightlang.Mirage] is a MirageOS
   unikernel. After [rocq c prog.light] has checked it, its
   [main : io unit] is extracted to OCaml into a MirageOS project, which is
   built for solo5's hvt target into [prog.hvt], next to [prog.vo].

   The project is kept between builds, in [$LIGHTLANG_MIRAGE_DIR] or else
   [~/.cache/lightlang/mirage], so that [mirage configure] and fetching the
   dependencies ([make depends]) only happen once. The MirageOS tools come
   from the opam switch [$LIGHTLANG_MIRAGE_SWITCH], [hvf] by default (a
   switch with the hvf-mac repository, see solo5-mac). Setting
   [LIGHTLANG_MIRAGE_BUILD=0] skips the image. *)

open Names

let mirage_library = DirPath.make (List.rev_map Id.of_string ["Lightlang"; "Mirage"])

(* [Library.library_is_loaded] is always true ([find_library] returns an
   option, it does not raise), so the list of loaded libraries is used *)
let requires_mirage () =
  List.exists (DirPath.equal mirage_library) (Library.loaded_libraries ())

let getenv_default var default =
  match Sys.getenv_opt var with Some v when v <> "" -> v | _ -> default

let project_dir () =
  match Sys.getenv_opt "LIGHTLANG_MIRAGE_DIR" with
  | Some d when d <> "" -> d
  | _ ->
    let cache = match Sys.getenv_opt "XDG_CACHE_HOME" with
      | Some d when d <> "" -> d
      | _ -> Filename.concat (getenv_default "HOME" ".") ".cache"
    in
    List.fold_left Filename.concat cache ["lightlang"; "mirage"]

let rec mkdir_p d =
  if not (Sys.file_exists d) then begin
    mkdir_p (Filename.dirname d);
    try Unix.mkdir d 0o755 with Unix.Unix_error (Unix.EEXIST, _, _) -> ()
  end

let read_file f =
  let ic = open_in_bin f in
  Fun.protect ~finally:(fun () -> close_in ic)
    (fun () -> really_input_string ic (in_channel_length ic))

let write_file f s =
  let oc = open_out_bin f in
  Fun.protect ~finally:(fun () -> close_out oc) (fun () -> output_string oc s)

(* Writes [f] only when its contents change, so that dune does not rebuild
   for nothing. Returns whether it changed. *)
let update_file f s =
  if Sys.file_exists f && String.equal (read_file f) s then false
  else (write_file f s; true)

let error msg = CErrors.user_err Pp.(str "Mirage: " ++ msg)

(* [main] exists and has type [io unit] *)
let check_main () =
  let main = Libnames.qualid_of_ident (Id.of_string "main") in
  let gr = try Nametab.locate main with Not_found ->
    error Pp.(str "a program that requires Mirage defines" ++ spc () ++
              str "main : io unit, what the unikernel does.")
  in
  let env = Global.env () in
  let ty, _ = Typeops.type_of_global_in_context env gr in
  let io = Nametab.global (Libnames.qualid_of_string "Lightlang.Mirage.io") in
  let unit = Rocqlib.lib_ref "core.unit.type" in
  let is r c = match Constr.kind c with
    | Constr.Ind (i, _) -> GlobRef.CanOrd.equal r (GlobRef.IndRef i)
    | _ -> false
  in
  let ok = match Constr.kind (Reduction.whd_all env ty) with
    | Constr.App (f, [| a |]) -> is io f && is unit (Reduction.whd_all env a)
    | _ -> false
  in
  if not ok then
    let sigma = Evd.from_env env in
    error Pp.(str "main has type" ++ spc () ++
              Printer.pr_lconstr_env env sigma ty ++ spc () ++
              str "but the unikernel runs an io unit.")

let config_ml = {lightlang|(* Generated by Lightlang (toplevel/lightlangMirage.ml): a Lightlang program
   as a MirageOS unikernel. unikernel.ml runs the program's [main],
   extracted to prog.ml. *)
open Mirage

let main = main "Unikernel" job ~packages:[ package "duration" ]
let () = register "lightlang" [ main ]
|lightlang}

let unikernel_ml = {lightlang|(* Generated by Lightlang (toplevel/lightlangMirage.ml): runs a Lightlang
   program's [main : io unit], extracted to prog.ml. Each [io] action
   becomes the unikernel's console, timers and loops. *)
open Lwt.Infix

let string_of_chars cs = String.of_seq (List.to_seq cs)

let int_of_nat n =
  let rec go acc = function Prog.O -> acc | Prog.S n -> go (acc + 1) n in
  go 0 n

(* [unk] and [raise] are values of gradual programs: running one is an
   error, reported as such *)
exception Stuck of string

let check v =
  if Gradual.is_unknown v then raise (Stuck "unk")
  else if Gradual.is_error v then raise (Stuck "raise")
  else v

let rec run : 'a. 'a Prog.io -> 'a Lwt.t = fun m ->
  match check m with
  | Prog.Ret a -> Lwt.return a
  | Prog.Bind (m, k) -> run m >>= fun x -> run (k x)
  | Prog.Print s ->
      print_string (string_of_chars (check s) ^ "\n");
      flush stdout;
      Lwt.return (Obj.magic ())
  | Prog.Sleep n ->
      Mirage_sleep.ns (Duration.of_sec (int_of_nat (check n))) >|= Obj.magic
  | Prog.Forever body ->
      let rec loop () = run body >>= loop in
      loop ()

let start () =
  Lwt.catch (fun () -> run Prog.main)
    (function
      | Stuck what -> Printf.printf "error: the program reached %s\n%!" what; exit 1
      | Gradual.Cast_error msg ->
          Printf.printf "error: a cast failed at run time (raise), %s\n%!" msg; exit 1
      | e -> Lwt.fail e)
|lightlang}

(* gradual.ml: the gradual runtime of prog.ml, which extraction only puts
   there when the program has casts, or a stand-in without errors *)
let gradual_ml ~has_casts =
  if has_casts then
    "(* Generated by Lightlang: prog.ml has casts *)\n\
     include Prog.Gradual_rt\n"
  else
    "(* Generated by Lightlang: prog.ml has no casts *)\n\
     exception Cast_error of string\n\
     let is_unknown _ = false\n\
     let is_error _ = false\n"

let has_substring s sub =
  let n = String.length sub in
  let rec at i = i + n <= String.length s && (String.sub s i n = sub || at (i + 1)) in
  at 0

(* Extracts [main] into [dir]/prog.ml, by running the extraction commands
   at the end of the program, after its .vo has been saved. *)
let extract ~state dir =
  let cmds = Filename.concat dir "extract.light" in
  write_file cmds (Printf.sprintf
    "Set Extraction Output Directory %S.\nExtraction \"prog\" main.\n" dir);
  Dumpglob.push_output Dumpglob.NoGlob;
  Fun.protect ~finally:Dumpglob.pop_output (fun () ->
      ignore (Vernac.load_vernac ~check:true ~state cmds))

let tail_of_file ?(lines = 20) f =
  try
    let all = String.split_on_char '\n' (read_file f) in
    let n = List.length all in
    String.concat "\n" (List.filteri (fun i _ -> i >= n - lines) all)
  with Sys_error _ -> ""

let copy_file ~src ~dst =
  write_file dst (read_file src);
  Unix.chmod dst 0o755

let build ~state ~vo_file =
  if getenv_default "LIGHTLANG_MIRAGE_BUILD" "1" <> "0" && requires_mirage () then begin
    check_main ();
    let dir = project_dir () in
    mkdir_p dir;
    let config_changed = update_file (Filename.concat dir "config.ml") config_ml in
    ignore (update_file (Filename.concat dir "unikernel.ml") unikernel_ml);
    extract ~state dir;
    let has_casts = has_substring (read_file (Filename.concat dir "prog.ml")) "module Gradual_rt" in
    ignore (update_file (Filename.concat dir "gradual.ml") (gradual_ml ~has_casts));
    let configured = Sys.file_exists (Filename.concat dir "Makefile") in
    let setup = if configured && not config_changed then ""
      else "mirage configure -t hvt && make depends && " in
    let switch = getenv_default "LIGHTLANG_MIRAGE_SWITCH" "hvf" in
    let log = Filename.concat dir "build.log" in
    let script = Printf.sprintf "cd %s && %smake build" (Filename.quote dir) setup in
    let cmd = Filename.quote_command "opam" ["exec"; "--switch=" ^ switch; "--"; "sh"; "-c"; script]
        ~stdout:log ~stderr:log in
    if setup <> "" then
      Feedback.msg_notice Pp.(str "Mirage: setting up the MirageOS project in " ++ str dir ++
                              str " (once; fetches the dependencies)");
    if Sys.command cmd <> 0 then
      error Pp.(str "building the image failed (opam switch " ++ str switch ++
                str "); the end of " ++ str log ++ str ":" ++ fnl () ++
                str (tail_of_file log));
    let hvt = Filename.remove_extension vo_file ^ ".hvt" in
    copy_file ~src:(List.fold_left Filename.concat dir ["dist"; "lightlang.hvt"]) ~dst:hvt;
    Feedback.msg_notice Pp.(str "Mirage: built " ++ str hvt ++
                            str "; run it with: solo5-hvt -- " ++ str hvt)
  end
