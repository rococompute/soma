(* Reusable native execution boundaries for Soma libraries. There is no
   project policy here: programs specify every primitive and continuation. *)
open Names

let loaded () =
  let name = DirPath.make (List.rev_map Id.of_string ["Soma"; "Native"]) in
  List.exists (DirPath.equal name) (Library.loaded_libraries ())

let extraction = {soma|
Extract Inductive Soma.Native.result => "Stdlib.result" [ "Stdlib.Ok" "Stdlib.Error" ].
Extract Inductive Soma.Native.progress => "Soma_effect.progress"
 [ "Soma_effect.Continue" "Soma_effect.Finish" ].
Extract Inductive Soma.Native.program => "Soma_effect.t"
 [ "Soma_effect.return" "Soma_effect.invoke" "Soma_effect.bind"
   "Soma_effect.loop" "Soma_effect.protect" "Soma_effect.throw"
   "Soma_effect.promise_return" "Soma_effect.promise_map"
   "Soma_effect.promise_bind" "Soma_effect.promise_catch"
   "Soma_effect.promise_finally" "Soma_effect.promise_fold" ]
 "(fun _ _ -> failwith ""a native program cannot be inspected"")".
Extract Inductive Soma.Native.entry => "Soma_effect.entry"
 [ "Soma_effect.export" ]
 "(fun _ _ -> failwith ""a native entry cannot be inspected"")".
Extract Constant Soma.Native.opaque => "Sys.opaque_identity".
|soma}

let ml = {soma|(* Generated by Soma: shared execution primitives for native libraries. *)
type 'a t = unit -> 'a
type 'a entry = 'a
type ('s, 'a) progress = Continue of 's | Finish of 'a
let return value () = value
let invoke (primitive, next) () = let value = primitive () in next value ()
let bind (before, next) () = let value = before () in next value ()
let loop (step, initial) () =
  let rec advance state = match step state () with
    | Continue state -> advance state
    | Finish value -> value in
  advance initial
let protect (body, recover) () = try body () with error -> recover error ()
let throw error () = raise error
let export body = body ()
let promise_return value () = Lwt.return value
let promise_map (body, next) () = let pending = body () in Lwt.map next pending
let promise_bind (body, next) () = let pending = body () in Lwt.bind pending next
let promise_catch (body, recover) () = Lwt.catch body recover
let promise_finally (body, cleanup) () = Lwt.finalize body cleanup
let promise_fold (step, initial, items) () = Lwt_list.fold_left_s step initial items
|soma}
