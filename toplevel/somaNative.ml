let ml = {soma|(* Generated by Soma: shared execution primitives for native libraries. *)
type 'a t = unit -> 'a
type 'a entry = 'a
type ('a, 'b) callback = 'a -> 'b
type 'a vector = 'a array
type text_buffer = Buffer.t
type ('k, 'v) table = ('k, 'v) Hashtbl.t
type ('s, 'a) progress = Continue of 's | Finish of 'a
let return value () = value
(* Fully enter a worker before the provider call. A partially applied thunk
   otherwise shares its closure environment with the still-live continuation,
   retaining the provider through callbacks it tailcalls. *)
let[@inline never] run_invoke primitive next = let value = primitive () in next value ()
let invoke (primitive, next) () = run_invoke primitive next
let bind (before, next) () = let value = before () in next value ()
let loop (step, initial) () =
  let rec advance state = match step state () with
    | Continue state -> advance state
    | Finish value -> value in
  advance initial
let protect (body, recover) () = try body () with error -> recover error ()
let throw error () = raise error
let export body = body ()
let promise_return value () = Lwt.return value
let[@inline never] run_map body next = let pending = body () in Lwt.map next pending
let promise_map (body, next) () = run_map body next
let[@inline never] run_bind body next = let pending = body () in Lwt.bind pending next
let promise_bind (body, next) () = run_bind body next
let promise_catch (body, recover) () = Lwt.catch body recover
let promise_finally (body, cleanup) () = Lwt.finalize body cleanup
let promise_fold (step, initial, items) () = Lwt_list.fold_left_s step initial items
let promise_map_s (step, items) () = Lwt_list.map_s step items
let promise_fail error () = Lwt.fail error
let new_reference value () = ref value
let read_reference location () = !location
let write_reference (location, value) () = location := value
let assert_failure (file, line, column) () = raise (Assert_failure (file, line, column))
(* Tailcall the list primitive after unpacking the effect, so its original
   input spine is not pinned while the primitive consumes it. *)
let[@inline never] run_filter predicate items = List.filter predicate items
let filter (predicate, items) () = run_filter predicate items
let new_callback body () =
  let rec self argument = export (body self argument) in self
let[@inline never] run_callback body argument = body argument
let call_callback (body, argument) () = run_callback body argument
let vector_of_list items () = Array.of_list items
let vector_to_list items () = Array.to_list items
let vector_length items () = Array.length items
let vector_get (items, index) () = Array.get items index
let vector_set (items, index, value) () = Array.set items index value
let new_text_buffer capacity () = Buffer.create capacity
let text_buffer_append (buffer, text) () = Buffer.add_string buffer text
let text_buffer_char (buffer, character) () = Buffer.add_char buffer character
let text_buffer_contents buffer () = Buffer.contents buffer
let new_table capacity () = Hashtbl.create capacity
let table_mem (entries, key) () = Hashtbl.mem entries key
let table_find (entries, key) () = Hashtbl.find entries key
let table_find_opt (entries, key) () = Hashtbl.find_opt entries key
let table_replace (entries, key, value) () = Hashtbl.replace entries key value
let table_remove (entries, key) () = Hashtbl.remove entries key
let[@inline never] run_string_map mapper text = String.map mapper text
let string_map (mapper, text) () = run_string_map mapper text
let string_get (text, index) () = String.get text index
let string_get_nat (text, index) () = String.get text index
let word_decimal value () = string_of_int value
let nat_decimal value () = string_of_int value
let path_basename path () = Filename.basename path
let path_dirname path () = Filename.dirname path
let path_concat (directory, file) () = Filename.concat directory file
let promise_apply body () = Lwt.apply body ()
|soma}
